--------------------------------------------------------------------------------
--- SpellHotReload.Adapters.Card.GeneratedBossScanner
---
--- Format gate for LuaSTG Editor Sharp generated Boss files. CardCallbacks owns
--- structural parsing and class/slot identity checks. This module only:
---   * rejects binary chunks / NUL bytes
---   * rejects files missing the generated header
---   * flags SC Debug output; its startup wiring is never executed
---   * collects `_editor_class[...]` class keys for the UI's match hint
--------------------------------------------------------------------------------

local IR=require("SpellHotReload.Source.TopLevelIR")
local Tree=require("SpellHotReload.Source.SyntaxTree")
local Scanner = {}

---@param content string
---@param file_name string
---@return table  -- { ok=boolean, error=string?, sc_debug=boolean, file_name=string }
function Scanner.Scan(content, file_name)
	local result = {
		ok = false,
		sc_debug = false,
		file_name = file_name,
	}

	if type(content) ~= "string" then
		result.error = "content is not a string"
		return result
	end

	-- strip a leading UTF-8 BOM (Editor Sharp writes files with one)
	if content:sub(1, 3) == "\239\187\191" then
		content = content:sub(4)
	end

	if content:find("\0", 1, true) then
		result.error = "binary chunk or NUL byte detected"
		return result
	end

	if not content:match("^%-%- Generated by LuaSTG Editor Sharp") then
		result.error = "missing LuaSTG Editor Sharp generated header"
		return result
	end

	if content:find("scdebugger", 1, true) then
		result.sc_debug = true
	end

	result.ok = true
	return result
end

---Collect class keys from index-expression nodes for the UI hint.
---A supplied snapshot must belong to these exact bytes; no token-pattern fallback.
function Scanner.ClassKeys(content,analysis)
    local keys={}
    if type(content)~="string" then return keys end
    local source=content
    if source:sub(1,3)=="\239\187\191" then source=source:sub(4) end
    if analysis then
        if analysis.source~=source or analysis.source_offset~=#content-#source or not analysis.syntax then return keys end
    else
        local nodes,reason;nodes,reason,analysis=IR.Analyze(content)
        if not nodes then return keys end
    end
    Tree.Walk(analysis.syntax,function(n)
        local key=Tree.ClassKey(n);if key then keys[key]=true end
    end)
    return keys
end
return Scanner
