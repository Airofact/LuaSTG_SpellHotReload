    local function state_at(snapshot,owner)
        for _,group in ipairs(snapshot.owners) do if group.owner==owner then return group.state end end
        error("original owner missing from actual snapshot")
    end
    local function local_state(f,snapshot)
        return snapshot and state_at(snapshot,Local) or must(Files.GetAdapterRecords(f.capture,Local)).state
    end
    local function card_state(f,snapshot)
        return snapshot and state_at(snapshot,Card) or must(Files.GetAdapterRecords(f.capture,Card)).state
    end
    local function observed(f,key,name)
        local values=must(Versions.Observations(f.capture.snapshot,must(Files.GetAdapterRecords(f.capture,Card)),key))
        for _,value in ipairs(values) do if value.name==name then return value.version end end
    end
    local function pending(f,kind,key,label)
        local model=must(f.p:GetCandidateRemainder(FILE))
        eq(model.complete,false,label.." incomplete")
        eq(model.revision,f.capture.snapshot.revision,label.." actual revision")
        local found
        for _,row in ipairs(model.pending) do
            if row.kind==kind and (key==nil or row.key==key) then found=row;break end
        end
        check(found~=nil,label.." exact pending item")
        return found
    end
    local function blocked(f,needle,label)
        local dependencies=must(f.prepared).driver_prepared.dependencies
        local found=false
        for _,root in ipairs(dependencies.blocked_roots) do
            if type(root.reason.message)=="string" and root.reason.message:find(needle,1,true) then found=true end
        end
        check(found,label.." actual blocked root reason")
    end
    local function no_op(f,base,label)
        eq(f.kernels,1,label.." one real common transaction")
        eq(#f.receipts,1,label.." genuine successful receipt")
        local recorded=must(f.receipts[1]);local receipt=recorded.receipt
        eq(receipt.kind,"SpellHotReload.FileCommit.Receipt",label.." receipt kind")
        eq(receipt.changed,false,label.." no changed definitions")
        eq(receipt.snapshot,base,label.." exact installed snapshot")
        eq(recorded.base,base,label.." actual base")
        eq(#receipt.owner_deltas,3,label.." both owner deltas")
        for _,fragment in ipairs(recorded.fragments) do
            eq(#fragment.joins+#fragment.cell_writes+#fragment.raw_writes,0,label.." owner no mutations")
            eq(fragment.proposed_group,fragment.base_group,label.." owner exact retained group")
        end
        eq(#recorded.fragments,3,label.." both owner fragments")
        eq(f.p._store:HasPartialPublication(FILE),false,label.." no partial publication")
        check(f.p._store:GetCandidate(FILE)~=nil,label.." pending candidate retained")
        eq(f.p._completion_checks[FILE],nil,label.." no completion witness")
        local last=must(f.discovered[#f.discovered])
        check(last.discovery~=f.prepared.driver_prepared.discovery,label.." fresh postreceipt discovery")
        eq(last.snapshot,base,label.." discovered actual retained snapshot")
        eq(last.source,recorded.source,label.." same complete source facts")
    end
    local function source_reason(f,key,needle,label)
        local discovery=must(f.prepared).driver_prepared.discovery
        local found=false
        for _,group in ipairs(discovery.reconciliation.groups) do
            if group.owner==Card then
                for _,row in ipairs(group.rows) do
                    if row.previous and row.previous.key==key and type(row.reason)=="string"
                        and row.reason:find(needle,1,true) then found=true end
                end
            end
        end
        check(found,label.." exact source-only Card evidence")
    end
    local function current_refused(f,needle,label)
        local result=f.p:ApplyFromUI()
        has(result,needle,label.." exact refusal")
        local deps=must(f.prepared).driver_prepared.dependencies
        eq(#deps.safe_roots,0,label.." requested root actually pruned")
        eq(#deps.blocked_roots,1,label.." one real blocked Current root")
        eq(deps.blocked_roots[1].root_id,f.prepared.target.key,label.." exact requested target")
        eq(deps.blocked_roots[1].unit_ref,f.prepared.operation.roots[1].unit_ref,label.." original unit identity")
        eq(f.freezes,0,label.." no frozen restart authorization")
        eq(f.kernels,0,label.." no transaction")
        eq(#f.receipts,0,label.." no receipt")
        eq(f.restarts,0,label.." no handoff")
        eq(f.p._pending_restart_run,nil,label.." no Retry request manufactured")
        eq(f.p._publication_error,nil,label.." refusal is not publication failure")
        eq(f.p._completion_checks[FILE],nil,label.." no completion witness")
        return result
    end
