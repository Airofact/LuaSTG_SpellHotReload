-- File-wide publication fixtures; no current-card requirement or restart. Only synthetic first-load chunks
-- execute; candidate top-level, card construction, and callback bodies never do.
-- Lua5.1 checks real missing-join refusal; only LuaJIT performs shared commits.
local M = {}
function M.run()
    local globals={"lstg","boss","_editor_class","_tmp_sc","_sc_table","ext","_va_runs","_va_api","jit","IsValid"}
    local saved={}
    for _,name in ipairs(globals) do saved[name]=rawget(_G,name) end
    local modules={"lstg.FileSystemWatcher","lstg.FileSystemWatcher.FileAction","SpellHotReload.Watcher","SpellHotReload.Plugin","imgui","SpellHotReload.Tab.MonitorTab"}
    local loaded={}
    for _,name in ipairs(modules) do loaded[name]=package.loaded[name] end
    package.loaded[modules[1]]={}
    package.loaded[modules[2]]={}
    package.loaded[modules[3]]=nil;package.loaded[modules[4]]=nil
    local Plugin=require("SpellHotReload.Plugin")
    local Load=require("SpellHotReload.AnchorLoad")
    local Anchor=require("SpellHotReload.Anchor")
    local Binding=require("SpellHotReload.PracticeBinding")
    local Compose=require("SpellHotReload.Compose")
    local Card=require("SpellHotReload.Card")
    local passed,failed,failures=0,0,{}
    local function check(v,label)
        if v then passed=passed+1 else failed=failed+1;failures[#failures+1]=label end
    end
    local function eq(a,b,label) check(a==b,label.." expected "..tostring(b)..", got "..tostring(a)) end
    local function has(s,p,label) check(type(s)=="string" and s:find(p,1,true)~=nil,label.." ("..tostring(s)..")") end
    local function must(v,err) assert(v,type(err)=="table" and err.message or err);return v end
    local get,set,join=debug.getupvalue,debug.setupvalue,debug.upvaluejoin
    local old_restart,old_plan,old_create=Binding.Restart,Card.Plan,Compose.Create
    local plugins,current={},nil
    local callbacks={"before","init","frame","render","beforedel","del","after"}
    local defaults={}
    for _,name in ipairs(callbacks) do defaults[name]=function() return "default" end end
    local FILE="Apply_Boss.lua"
    local SIDE=table.concat({
        "_editor_class['L'].cards={}",
        "_tmp_sc=boss.card.New('C',1,2,3,100)",
        "function _tmp_sc:init(n) return helper(n)+300 end",
        "table.insert(_editor_class['L'].cards,_tmp_sc)",
    },"\n")
    local SOURCE=table.concat({
        "-- Generated by LuaSTG Editor Sharp",
        "local state=4",
        "local function helper(n) return state+n end",
        "local function idle(n) return n+1000 end",
        "local function setstate(v) state=v end",
        "_va_runs=_va_runs+1","_va_api={set=setstate}",
        "_editor_class['K'].cards={boss.move.New(0,0,1)}",
        "_tmp_sc=boss.card.New('A',1,2,3,100)",
        "function _tmp_sc:init(n) return helper(n) end",
        "table.insert(_editor_class['K'].cards,_tmp_sc)",
        "_tmp_sc=boss.card.New('B',1,2,3,100)",
        "function _tmp_sc:init(n) return helper(n)+100 end",
        "table.insert(_editor_class['K'].cards,_tmp_sc)",
        SIDE,
    },"\n")
    local EDIT=SOURCE:gsub("state=4","state=999"):gsub("state%+n end","state+n+10 end")
        :gsub("n%+1000","n+2000"):gsub("helper%(n%)%+100","helper(n)+200")
    local function enter(f,slot,mode)
        slot=slot or 2
        _sc_table[1]={"K",f.classes.K.cards[slot].name,f.classes.K.cards[slot],slot,false}
        lstg.var.sc_index=1
        f.mode=mode or "practice"
    end
    local function candidate(f,content)
        f.disk=content
        local c=f.p._store:BeginCandidate(FILE,f.p._store._next_generation,"spec")
        must(f.p._store:RecordFirstRead(FILE,c.generation,content,1))
        return must(f.p._store:VerifyStable(FILE,c.generation,content,2,1))
    end
    local function fixture()
        debug.getupvalue,debug.setupvalue,debug.upvaluejoin=get,set,join
        _G.jit=saved.jit
        _va_runs=0
        _G.IsValid=function() return true end
        _editor_class={K={},L={}}
        _sc_table={}
        ext={replay={IsReplay=function() return current and current.replay==true end}}
        lstg={var={},Log=function() end,FileManager={EnumFiles=function() return {{FILE,false}} end}}
        local f={constructions=0,restarts=0,reads=0,discoveries=0,creates=0,legacy=0,classes=_editor_class}
        current=f
        boss={card={_default_card=defaults,New=function(name)
            f.constructions=f.constructions+1
            local c={name=name,is_combat=true}
            for _,cb in ipairs(callbacks) do c[cb]=defaults[cb] end
            return c
        end},move={New=function() return {is_combat=false} end}}
        f.p=Plugin.New();plugins[#plugins+1]=f.p
        f.entry=must(Load.Capture(SOURCE,{name=FILE}))
        must(f.p:AdoptLoad(FILE,f.entry))
        f.capture=f.p:GetVersions(FILE)
        f.p._activated,f.p._supported=true,true
        f.p._activation_attempted=true
        f.p._sandbox_ok=join~=nil
        f.p._sandbox_error="shared-cell debug APIs unavailable"
        f.disk=EDIT
        f.p._store:SetAccepted(FILE,SOURCE,"baseline")
        local Watcher=require("SpellHotReload.Watcher")
        f.p._watcher=Watcher.New({root="mod/Test",store=f.p._store,quiet_frames=1,read_gap=1,drift_interval=5})
        f.p._watcher.ReadFile=function()
            f.reads=f.reads+1
            if f.on_read then f.on_read(f) end
            return f.disk
        end
        candidate(f,EDIT)
        enter(f,2)
        local driver=f.p._driver
        local discover=driver.Discover
        driver.Discover=function(self,...)
            f.discoveries=f.discoveries+1
            if f.on_discover then f.on_discover(f) end
            return discover(self,...)
        end
        local function legacy() f.legacy=f.legacy+1;error("legacy publication forbidden") end
        driver.Commit,driver.Restart,f.p._Publish,f.p._registry.SetAll,f.p._anchors.SetAll=legacy,legacy,legacy,legacy,legacy
        Card.Plan=legacy
        Binding.Restart=function(class_key,name,card,slot,include_previous)
            f.restarts=f.restarts+1
            f.restart_args={class_key,name,card,slot,include_previous}
            if f.on_restart then f.on_restart(f) end
            _sc_table.EXT_POS={class_key,name,card,slot,include_previous}
            lstg.var.sc_index="EXT_POS"
        end
        Compose.Create=function(...)
            f.creates=f.creates+1
            if f.on_create then f.on_create(f) end
            return old_create(...)
        end
        return f
    end
    local function unchanged(f,base,label)
        eq(f.capture.snapshot,base,label.." snapshot unchanged")
        eq(Anchor.Get(f.entry,"helper"),base.functions.units.helper.fn,label.." cell unchanged")
        for _,key in ipairs(base.order) do
            local unit=base.units[key]
            for _,name in ipairs(callbacks) do eq(rawget(unit.card,name),unit.callbacks[name].fn,label.." raw "..key..name) end
        end
        eq(f.p._store:HasPartialPublication(FILE),false,label.." no partial record")
        eq(f.restarts,0,label.." no restart")
        eq(f.legacy,0,label.." no fallback")
    end
    local ok,problem=pcall(function()
        local f=fixture()
        if not join then
            has(f.p:ApplyFileFromUI(FILE),"patch capability unavailable","real Lua5.1 refusal")
            eq(f.restarts,0,"missing join never restarts")
            eq(f.legacy,0,"missing join never falls back")
        else
            local base=f.capture.snapshot
            _sc_table={};lstg.var.sc_index=nil -- deliberately no current practice
            _va_api.set(9)
            has(f.p:ApplyFile(FILE),"versioned UI scope","direct unscoped file Apply refused")
            unchanged(f,base,"unscoped file Apply")
            has(f.p:ApplyFileFromUI("Unknown_Boss.lua"),"stable candidate required","explicit file required")
            -- A different unowned candidate must not affect the named-file operation.
            local other=f.p._store:BeginCandidate("Other_Boss.lua",f.p._store._next_generation,"spec")
            must(f.p._store:RecordFirstRead("Other_Boss.lua",other.generation,EDIT,1))
            must(f.p._store:VerifyStable("Other_Boss.lua",other.generation,EDIT,2,1))
            has(f.p:ApplyFileFromUI(FILE),"definitions committed; no restart","file Apply without current card")
            eq(f.restarts,0,"file Apply no practice handoff")
            eq(f.p:HasRestartPending(),false,"no frozen restart retained")
            eq(f.capture.snapshot.revision,1,"one atomic file publication")
            eq(f.capture.snapshot.anchor,base.anchor,"same state anchor")
            eq(f.capture.snapshot.loaded_source,SOURCE,"load baseline retained")
            eq(Anchor.Get(f.entry,"state"),9,"initializer not replayed")
            eq(Anchor.Get(f.entry,"idle")(1),2001,"unreferenced captured helper published")
            eq(f.classes.K.cards[2]:init(1),20,"first class callback reads new helper")
            eq(f.classes.K.cards[3]:init(1),220,"sibling edited wrapper published")
            eq(f.classes.L.cards[1]:init(1),320,"other captured class helper propagation")
            eq(f.capture.snapshot.units["card:1:K:3"].definition_version,2,"changed wrapper version advanced")
            eq(f.capture.snapshot.units["card:1:L:1"].definition_version,1,"helper-only wrapper version retained")
            eq(f.p._store:GetAccepted(FILE).content,SOURCE,"no whole-file ACK")
            eq(f.p._store:GetCandidate(FILE).first_content,EDIT,"unsupported initializer candidate retained")
            check(f.p._store:GetCandidate("Other_Boss.lua")~=nil,"unrelated candidate retained")
            eq(f.p._store:GetPartialPublication(FILE).revision,1,"publication ledger reflects actual commit")
            eq(_va_runs,1,"top-level initialization still once")
            eq(f.constructions,3,"no construction or registration replay")
            eq(f.legacy,0,"no legacy fallback")
            local published=f.capture.snapshot
            has(f.p:ApplyFileFromUI(FILE),"no definition changes; no restart","repeat file Apply no-op")
            eq(f.capture.snapshot,published,"no-op has no manufactured version")
            candidate(f,EDIT:gsub("state%+n%+10 end","state+n+20 end"))
            has(f.p:ApplyFileFromUI(FILE),"definitions committed; no restart","second file revision")
            eq(f.capture.snapshot.revision,2,"second changed publication only once")
            eq(f.classes.K.cards[3]:init(1),230,"second helper edit live")
            eq(Anchor.Get(f.entry,"state"),9,"state preserved through two Apply")
            eq(f.restarts,0,"both file transactions no restart")
            f.p:Dismiss("Other_Boss.lua") -- avoid intentionally duplicated current class in legacy fixture
            enter(f,2)
            has(f.p:ApplyFromUI(),"no definition changes","existing current restart remains available")
            eq(f.restarts,1,"only separate current action restarts")
            local reads,creates,discoveries=f.reads,f.creates,f.discoveries
            Binding.Restart=function() f.restarts=f.restarts+1;error("restart fault") end
            has(f.p:ApplyFromUI(),"restart failed","separate restart fault")
            eq(f.p:HasRestartPending(),true,"failed current restart retained")
            has(f.p:ApplyFileFromUI(FILE),"retry restart first","file Apply cannot invalidate pending retry")
            check(f.reads>=reads,"current Apply performed fresh analysis")
            -- Above current Apply still analyzes. Verify Retry separately from its final counts.
            reads,creates,discoveries=f.reads,f.creates,f.discoveries
            Binding.Restart=function() f.restarts=f.restarts+1 end
            eq(f.p:RetryRestartFromUI(),"restarted","retry current handoff")
            eq(f.reads,reads,"Retry no disk");eq(f.creates,creates,"Retry no compile")
            eq(f.discoveries,discoveries,"Retry no discovery")
            local faults={"disk","generation","missing","replay","layout","syntax","setter","flush"}
            for _,fault in ipairs(faults) do
                f=fixture();base=f.capture.snapshot
                if fault=="disk" then f.disk=EDIT.."\n-- external drift"
                elseif fault=="generation" then
                    f.on_create=function()
                        f.on_create=nil;candidate(f,EDIT)
                    end
                elseif fault=="missing" then f.p:Missing(FILE)
                elseif fault=="replay" then f.replay=true
                elseif fault=="layout" then candidate(f,EDIT:gsub(SIDE:gsub("([^%w])","%%%1"),""))
                elseif fault=="syntax" then candidate(f,EDIT.."\nfunction broken(")
                elseif fault=="setter" then
                    debug.setupvalue=function(fn,index,v)
                        if fn==f.entry.anchor then
                            set(fn,index,v)
                            if v~=base.functions.units.helper.fn then error("throw after write") end
                        end
                        return set(fn,index,v)
                    end
                else
                    _G.jit={flush=function() f.disk=EDIT.."\n-- during flush" end}
                end
                local result=f.p:ApplyFileFromUI(FILE)
                check(result:sub(1,7)~="applied",fault.." must not report success")
                unchanged(f,base,fault.." failure")
                debug.setupvalue=set;_G.jit=saved.jit
            end
            f=fixture();base=f.capture.snapshot
            f.p._store.RecordPartialPublication=function() return nil,"bookkeeping fault" end
            has(f.p:ApplyFileFromUI(FILE),"definitions committed; partial publication bookkeeping failed","postcommit fact preserved")
            eq(f.capture.snapshot.revision,1,"bookkeeping fault does not roll history back")
            eq(f.p:HasRestartPending(),false,"file Apply never manufactures a retry")
            has(f.p:ApplyFileFromUI(FILE),"bookkeeping failed","postcommit sticky refusal")
            eq(f.restarts,0,"bookkeeping failure no restart")
            -- Layout stub proves the two scopes and adjacent per-file buttons.
            local labels,clicks={},{}
            package.loaded.imgui={ImVec4=function(...) return {...} end,ImGui={
                Text=function() end,TextDisabled=function() end,TextWrapped=function() end,
                TextColored=function() end,Separator=function() end,
                SameLine=function() labels[#labels+1]="<same-line>" end,
                CollapsingHeader=function() return false end,
                Button=function(label) labels[#labels+1]=label;return clicks[label] or false end}}
            local ui_name="SpellHotReload.Tab.MonitorTab"
            local old_imgui,old_ui=loaded.imgui,package.loaded[ui_name]
            package.loaded[ui_name]=nil
            local Monitor=require(ui_name)
            f=fixture()
            _sc_table={};lstg.var.sc_index=nil
            clicks["Apply##apply_file_"..FILE]=true
            local view={plugin=f.p};Monitor.layout(view)
            has(view.last_result,"definitions committed; no restart","row button uses named scoped file Apply")
            eq(f.restarts,0,"row button never restarts current")
            local text=table.concat(labels,"\n")
            has(text,"Apply##apply_file_"..FILE.."\n<same-line>\nDismiss##dismiss_1","Apply adjacent to Dismiss")
            check(not text:find("Apply & Restart Current",1,true),"global current action unavailable without current")
            clicks={};labels={};f.p._pending_restart_run={kind="versioned-card-restart"}
            Monitor.layout(view)
            check(not table.concat(labels,"\n"):find("Apply##apply_file_",1,true),"pending retry disables file buttons")
            package.loaded.imgui=old_imgui;package.loaded[ui_name]=old_ui
        end
    end)
    debug.getupvalue,debug.setupvalue,debug.upvaluejoin=get,set,join
    Binding.Restart,Card.Plan,Compose.Create=old_restart,old_plan,old_create
    for _,p in ipairs(plugins) do p:Release() end
    for _,name in ipairs(modules) do package.loaded[name]=loaded[name] end
    for _,name in ipairs(globals) do rawset(_G,name,saved[name]) end
    if not ok then failed=failed+1;failures[#failures+1]="unexpected error: "..tostring(problem) end
    print(string.format("FileApplySpec: %d passed / %d failed",passed,failed))
    for _,why in ipairs(failures) do print("  FAIL "..why) end
    return {passed=passed,failed=failed}
end
return M
