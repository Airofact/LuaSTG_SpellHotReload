local Planning=require("SpellHotReload.tests.PlanningFixture")
-- Exact owner registration, one real common receipt, then frozen restart only.
-- Miniature genuine first loads; no engine or readiness claim.
local M={}
local serial=0
function M.run()
    local Card=require("SpellHotReload.Adapters.Card.Card")
    local Local=require("SpellHotReload.Adapters.Local.Local")
    local Load=require("SpellHotReload.Load.AnchorLoad")
    local Files=require("SpellHotReload.Pipeline.FileVersions")
    local Commit=require("SpellHotReload.Apply.FileCommit")
    local FileApply=require("SpellHotReload.Apply.FileApply")
    local Source=require("SpellHotReload.Source.FileAnalysis")
    local Compose=require("SpellHotReload.Source.Compose")
    local Anchor=require("SpellHotReload.Load.Anchor")
    local Binding=require("SpellHotReload.Adapters.Card.PracticeBinding")
    local Restart=require("SpellHotReload.Runtime.CurrentRestart")
    local Callbacks=require("SpellHotReload.Adapters.Card.CardCallbacks")
    local passed,failed,failures=0,0,{}
    local function check(v,label)
        if v then passed=passed+1 else failed=failed+1;failures[#failures+1]=label end
    end
    local function eq(a,b,label) check(rawequal(a,b),label) end
    local function has(s,p,label) check(type(s)=="string" and s:find(p,1,true)~=nil,label) end
    local function must(v,e) assert(v,type(e)=="table" and e.message or e);return v,e end
    local function copy(v) local out={};for k,x in next,v do out[k]=x end;return out end
    local function refuse(call,phase,label,code)
        local called,v,e=pcall(call)
        eq(called,true,label.." no throw");eq(v,nil,label.." refusal")
        eq(type(e),"table",label.." structured")
        if type(e)=="table" then
            eq(e.phase,phase,label.." phase");check(type(e.message)=="string",label.." message")
            if code then eq(e.code,code,label.." code") end
        end
        return e
    end
    local globals={"boss","_editor_class","_tmp_sc","_handoff_runs","jit","lstg"}
    local saved={};for _,key in ipairs(globals) do saved[key]=rawget(_G,key) end
    local join,set=debug.upvaluejoin,debug.setupvalue
    local handoff,replay,current=Restart.Handoff,Binding.IsReplay,Binding.CaptureCurrent
    local commit_hook,local_hook,restart_hook,publish=Card.Commit,Local.Commit,Restart.Request,Callbacks.Publish
    local create_hook,build_hook=Compose.Create,Source.Build
    local modules={"SpellHotReload.Runtime.Plugin","SpellHotReload.Runtime.Watcher",
        "lstg.FileSystemWatcher","lstg.FileSystemWatcher.FileAction"}
    local loaded={};for _,key in ipairs(modules) do loaded[key]=package.loaded[key] end
    local controllers,plugins={},{}
    local defaults={}
    for _,name in ipairs({"before","init","frame","render","beforedel","del","after"}) do defaults[name]=function() end end
    local function source(n)
        return table.concat({
            "-- Generated by LuaSTG Editor Sharp",
            "local state=4",
            "local function helper(n) return state+n+"..n.." end",
            "_handoff_runs=_handoff_runs+1",
            "_editor_class['K'].cards={}",
            "_tmp_sc=boss.card.New('A',1,2,3,4)",
            "function _tmp_sc:init(n) return helper(n)+10 end",
            "table.insert(_editor_class['K'].cards,_tmp_sc)",
            "_tmp_sc=boss.card.New('B',1,2,3,4)",
            "function _tmp_sc:init(n) return helper(n)+20 end",
            "table.insert(_editor_class['K'].cards,_tmp_sc)",
        },"\n")
    end
    local function reset_hooks()
        Card.Commit,Local.Commit,Restart.Request,Callbacks.Publish=commit_hook,local_hook,restart_hook,publish
        Restart.Handoff,Binding.IsReplay,Binding.CaptureCurrent=handoff,replay,current
        Compose.Create,Source.Build=create_hook,build_hook
        debug.upvaluejoin,debug.setupvalue=join,set;rawset(_G,"jit",saved.jit)
    end
    -- Shared startup only: each fixture has exactly one authoritative capture.
    local function first_load()
        reset_hooks();serial=serial+1
        _handoff_runs=0;_editor_class={K={}}
        boss={card={_default_card=defaults,New=function(name)
            local c={name=name,is_combat=true};for k,fn in next,defaults do c[k]=fn end;return c
        end}}
        local entry=must(Load.Capture(source(0),{name="Handoff_Boss.lua"}))
        must(entry.reloadable,entry.reason);entry.file="Handoff_Boss.lua"
        local initial={class_key="K",slot=1,name="A",card=_editor_class.K.cards[1],
            names={"A","B"},mode="practice",include_previous=false}
        return {entry=entry,initial=initial,classes=_editor_class}
    end
    local function record(p,owner)
        for _,r in ipairs(p.entries) do if r.owner==owner then return r end end
        error("missing genuine owner record")
    end
    local function fragments(p)
        local out={};for _,r in ipairs(p.entries) do out[#out+1]=r.fragment end;return out
    end
    local function fixture()
        local f=first_load()
        f.fixture=must(Planning.Capture(f.entry,"handoff:"..serial,f.classes,defaults))
        f.capture=f.fixture.capture;f.base=f.capture.snapshot
        f.live={capture=f.capture,snapshot=f.base,entry=f.entry,classes=f.classes,
            session_id=f.base.session_id,content=source(5),binding=f.initial,generation=3}
        f.fresh=0;f.fixture.refresh=function() f.fresh=f.fresh+1;return f.live end
        f.discovery=must(Planning.Discover(f.fixture,must(Source.Build(f.live.content)),3))
        f.prepared=must(Planning.Prepare(f.fixture,f.discovery,{mode="current",refresh=f.fixture.refresh}))
        eq(#f.prepared.dependencies.safe_roots,1,"real Current root safe")
        eq(#f.prepared.dependencies.blocked_roots,0,"no blocked root hides handoff")
        f.target=f.prepared.operation.card.target
        return f
    end
    local function controller(f)
        local tx=must(Commit.New(f.base.session_id));controllers[#controllers+1]=tx;return tx
    end
    local function lifecycle(f) return {session_id=f.base.session_id,entry=f.entry,classes=f.classes} end
    local function unchanged(f,old,label)
        eq(f.capture.snapshot,f.base,label.." actual snapshot retained")
        eq(f.initial.card.init,old,label.." raw callback retained")
        eq(Anchor.Get(f.entry,"helper")(1),5,label.." old helper cell retained")
        eq(_handoff_runs,1,label.." no miniature source replay")
    end
    local traps,legacy=0,0
    local hostile=setmetatable({},{__index=function() traps=traps+1;error("hostile index") end,
        __tostring=function() traps=traps+1;error("hostile stringify") end})
    local ok,problem=pcall(function()
        must(Anchor.Supported(Compose.Capability(debug)))
        local f=fixture();local p=f.prepared;local r=record(p,Card)
        local h,fragment,ctx=r.handle,r.fragment,r.context
        local original=f.initial.card.init
        eq(h.operation,p.operation,"owner handle has original operation")
        eq(fragment.operation,p.operation,"fragment has original operation")
        eq(ctx.common,f.discovery.snapshot.common,"common stays original")
        eq(ctx.common.transaction,nil,"no common transaction capability")
        eq(ctx.common.register,nil,"no common registrar")
        eq(ctx.adapter.file.register,nil,"discovery scope has no registrar")
        eq(ctx.adapter.transaction,nil,"no owner publisher")
        eq(#record(p,Local).fragment.cell_writes,1,"genuine helper update")
        eq(#fragment.raw_writes,0,"unchanged Card wrappers are not recompiled")
        Callbacks.Publish=function() legacy=legacy+1;error("legacy publication forbidden") end
        refuse(function() return Card.Commit(h,fragment,ctx) end,"register","missing registrar","ownership")
        ctx.adapter.register=hostile
        refuse(function() return Card.Commit(h,fragment,ctx) end,"register","nonfunction registrar","ownership")
        ctx.adapter.register=nil
        refuse(function() return Card.Commit(hostile,fragment,ctx) end,"register","hostile handle","ownership")
        refuse(function() return Card.Commit(h,hostile,ctx) end,"register","hostile fragment","ownership")
        local calls,registrations,retained=0,0
        local marker={phase="commit",code="rollback",message="transaction refused"}
        Local.Commit=function(a,b,c)
            registrations=registrations+1;eq(calls,0,"Local registers before publisher")
            return local_hook(a,b,c)
        end
        Card.Commit=function(a,b,c)
            registrations=registrations+1;eq(calls,0,"Card registers before publisher")
            eq(a,h,"exact real Card handle");eq(b,fragment,"exact real Card fragment");eq(c,ctx,"exact real Card context")
            retained=c.adapter.register
            local function count(...) return select("#",...),... end
            local n,registered=count(commit_hook(a,b,c))
            eq(n,1,"Card hook single result");eq(registered,true,"Card hook only registers")
            return registered
        end
        local value,err=f.fixture.driver:CommitDiscovery(p,function(op,all)
            calls=calls+1;eq(registrations,2,"both owners registered first")
            eq(op,p.operation,"unique publisher operation");eq(#all,2,"publisher complete owner set")
            for i,row in ipairs(p.entries) do
                eq(all[i],row.fragment,"exact registered fragment")
                eq(row.context.adapter.register,nil,"registrar revoked before publisher")
            end
            return nil,marker
        end)
        eq(value,nil,"transaction refusal forwarded");eq(err,marker,"transaction error identity preserved")
        eq(calls,1,"exactly one publisher callback");eq(registrations,2,"both real hooks called")
        refuse(function() return retained(h,fragment,ctx) end,"register","expired registrar","stale")
        unchanged(f,original,"registration-only");eq(legacy,0,"no legacy publication")
        reset_hooks()
        -- Identity failures use the REAL bound registrar, in separate operations.
        -- A foreign attempt poisons that registration; never probe a success path.
        for _,kind in ipairs({"copied fragment","foreign context","foreign handle","hostile handle","hostile fragment"}) do
            f=fixture();p=f.prepared;original=f.initial.card.init;calls=0
            local inner_error
            Card.Commit=function(a,b,c)
                local x,y,z=a,b,c
                if kind=="copied fragment" then y=copy(b)
                elseif kind=="foreign context" then z=copy(c)
                elseif kind=="foreign handle" then x={}
                elseif kind=="hostile handle" then x=hostile else y=hostile end
                local v,e=commit_hook(x,y,z);inner_error=e;return v,e
            end
            refuse(function() return f.fixture.driver:CommitDiscovery(p,function() calls=calls+1 end) end,
                "register",kind,"ownership")
            eq(type(inner_error),"table",kind.." inner policy diagnostic")
            eq(calls,0,kind.." zero transactions")
            unchanged(f,original,kind)
            for _,row in ipairs(p.entries) do eq(row.context.adapter.register,nil,kind.." scope revoked") end
        end
        reset_hooks()

        -- Missing join is injected AFTER a genuine supported preparation.
        f=fixture();p=f.prepared;original=f.initial.card.init
        local tx=controller(f);debug.upvaluejoin=nil
        local receipt,why=Planning.Publish(f.fixture,p,tx)
        eq(receipt,nil,"real missing join refused");eq(why.code,"capability","real kernel capability refusal")
        unchanged(f,original,"missing join");eq(tx:Poisoned(),false,"capability refusal not poison")
        reset_hooks()
        f=fixture();p=f.prepared;original=f.initial.card.init;tx=controller(f)
        Callbacks.Publish=function() legacy=legacy+1;error("legacy publication forbidden") end
        local run=must(Restart.Freeze(f.target,f.capture))
        local failed_run=must(Restart.Freeze(f.target,f.capture))
        local engine=0;Binding.IsReplay=function() return false end
        Restart.Handoff=function() engine=engine+1 end
        refuse(function() return Restart.Request(run,lifecycle(f)) end,"restart","uncommitted run","restart")
        eq(engine,0,"uncommitted run cannot reach engine")
        receipt,why=f.fixture.driver:CommitDiscovery(p,function(op,all)
            return tx:Commit({},op,all,f.live,FileApply.Refresh(op,f.fixture.refresh))
        end)
        eq(receipt,nil,"foreign token refused");eq(why.code,"phase","kernel owns phase authority")
        unchanged(f,original,"foreign token")
        local saved_token;local run_scope=tx.Run
        tx.Run=function(self,callback,...)
            return run_scope(self,function(token,...) saved_token=token;return callback(token,...) end,...)
        end
        receipt=must(Planning.Publish(f.fixture,p,tx));tx.Run=run_scope
        eq(receipt.kind,"SpellHotReload.FileCommit.Receipt","actual common receipt")
        eq(receipt.changed,true,"actual helper publication changed")
        eq(receipt.snapshot,f.capture.snapshot,"actual installed snapshot returned")
        eq(f.capture.snapshot.revision,1,"one common revision")
        eq(#receipt.owner_deltas,2,"complete owner deltas")
        eq(receipt.owner_deltas[1].owner,Local,"Local delta owner")
        eq(receipt.owner_deltas[1].changed,true,"Local helper changed")
        eq(receipt.owner_deltas[2].owner,Card,"Card delta owner")
        eq(receipt.owner_deltas[2].changed,false,"Card wrappers unchanged")
        eq(f.capture.snapshot.owners[2],f.base.owners[2],"unchanged actual Card group retained")
        eq(f.initial.card:init(1),20,"current callback reads new helper")
        eq(f.classes.K.cards[2]:init(1),30,"unselected callback sees shared propagation")
        eq(f.classes.K.cards[2].init,f.base.owners[2].state.units["card:1:K:2"].callbacks.init.fn,"unselected wrapper retained")
        eq(f.initial.card.init,original,"selected unchanged wrapper retained")
        eq(Anchor.Get(f.entry,"state"),4,"state preserved");eq(_handoff_runs,1,"no source replay")
        eq(f.fresh,4,"initial binding/locate plus prepublish/final refresh")
        refuse(function() return tx:Check(saved_token) end,"commit","scope expired","stale")
        calls=0
        refuse(function() return f.fixture.driver:CommitDiscovery(p,function() calls=calls+1 end) end,
            "register","old prepared publication refused","ownership")
        eq(calls,0,"old plan no second publisher")
        refuse(function() return Restart.BindReceipt(run,{snapshot=receipt.snapshot},f.capture) end,
            "restart","snapshot-only fake receipt","restart")
        eq(run.state,"prepared","bad receipt does not bind")
        refuse(function() return Restart.BindReceipt(copy(run),receipt,f.capture) end,
            "restart","copied run lacks private proof","restart")
        must(Restart.BindReceipt(run,receipt,f.capture));must(Restart.BindReceipt(failed_run,receipt,f.capture))
        local restarts=0
        Restart.Handoff=function(key,name,card,slot,previous)
            restarts=restarts+1;eq(key,"K","frozen class");eq(name,"A","frozen name")
            eq(card,f.initial.card,"frozen card");eq(slot,1,"frozen slot");eq(previous,false,"frozen prefix")
        end
        eq(Restart.Request(run,lifecycle(f)),true,"committed restart accepted")
        eq(run.ready,"unobserved","acceptance not Boss readiness")
        f.entry.missing,f.entry.reloadable=true,false
        eq(Restart.Request(run,lifecycle(f)),true,"accepted Missing run revalidated")
        eq(restarts,1,"accepted request never handed off twice")
        eq(run.selection,nil,"run retains no selection");eq(run.discovery,nil,"run retains no discovery")
        eq(run.context,nil,"run retains no transaction context")
        refuse(function() return Restart.Request(run,p) end,"restart","plan is not lifecycle","restart")
        local wrong=lifecycle(f);wrong.session_id="foreign"
        refuse(function() return Restart.Request(run,wrong) end,"restart","foreign restart context","restart")
        Binding.IsReplay=function() return true end
        refuse(function() return Restart.Request(run,lifecycle(f)) end,"restart","accepted replay refused","restart")
        Binding.IsReplay=function() return false end
        Restart.Handoff=function() error("restart fixture") end
        why=refuse(function() return Restart.Request(failed_run,lifecycle(f)) end,"restart","handoff error","restart")
        has(why.message,"restart fixture","original engine error preserved")
        eq(failed_run.state,"failed","failed request retained");eq(failed_run.attempts,1,"one failed attempt")
        Restart.Handoff=function() restarts=restarts+1 end
        eq(Restart.Request(failed_run,lifecycle(f)),true,"failed Missing run retries only restart")
        eq(failed_run.attempts,2,"retry attempt recorded")
        eq(f.capture.snapshot,receipt.snapshot,"restart never republishes")
        eq(traps,0,"no hostile callbacks")

        package.loaded[modules[3]],package.loaded[modules[4]]={},{}
        package.loaded[modules[1]],package.loaded[modules[2]]=nil,nil
        local Plugin=require("SpellHotReload.Runtime.Plugin")
        local function plugin_fixture()
            local x=first_load()
            lstg={var={},Log=function() end}
            x.plugin=Plugin.New();plugins[#plugins+1]=x.plugin
            must(x.plugin:AdoptLoad(x.entry.file,x.entry))
            x.capture=must(x.plugin:GetVersions(x.entry.file));x.base=x.capture.snapshot
            must(Files.Validate(x.capture))
            local p=x.plugin
            p._activated,p._supported,p._sandbox_ok=true,true,true
            p._activation_attempted=true
            x.reads=0
            p._watcher={ReadFile=function() x.reads=x.reads+1;return source(5) end}
            p._store:SetAccepted(x.entry.file,source(0),"baseline")
            local candidate=p._store:BeginCandidate(x.entry.file,3,"handoff")
            must(p._store:RecordFirstRead(x.entry.file,candidate.generation,source(5),1))
            must(p._store:VerifyStable(x.entry.file,candidate.generation,source(5),2,1))
            x.candidate=must(p._store:GetCandidate(x.entry.file))
            Binding.CaptureCurrent=function() return x.initial end
            Binding.IsReplay=function() return false end
            Callbacks.Publish=function() legacy=legacy+1;error("legacy publication forbidden") end
            return x
        end
        f=plugin_fixture()
        local plugin=f.plugin
        local commits,kernels,requests,engine=0,0,0,0
        eq(Card.Restart,nil,"production has no adapter restart hook")
        eq(Binding.Restart,nil,"production has no legacy handoff facade")
        Card.Commit=function(a,b,c)
            commits=commits+1
            eq(a.operation,c.operation,"production original handle operation")
            eq(b.operation,c.operation,"production original fragment operation")
            eq(b.owner,Card,"production original Card fragment")
            eq(type(c.adapter.register),"function","production bound registrar")
            eq(c.adapter.transaction,nil,"production owner has no publisher")
            eq(c.common.transaction,nil,"production common has no publisher")
            eq(kernels,0,"production registers before kernel")
            return commit_hook(a,b,c)
        end
        local kernel=plugin._commit.Commit
        local actual_receipt
        plugin._commit.Commit=function(self,...)
            kernels=kernels+1
            eq(commits,1,"kernel follows Card registration")
            local receipt,err=kernel(self,...);actual_receipt=receipt;return receipt,err
        end
        Restart.Request=function(run,view)
            requests=requests+1
            eq(run.receipt,actual_receipt,"production uses actual common receipt")
            eq(run.receipt.snapshot,run.snapshot,"production committed snapshot")
            eq(view.entry,run.entry,"production frozen lifecycle entry")
            eq(plugin._restart_active,true,"busy spans workflow request")
            return restart_hook(run,view)
        end
        Restart.Handoff=function() engine=engine+1;error("engine retry fixture") end
        local result=plugin:ApplyFromUI()
        has(result,"definitions committed; restart failed:","production restart fails after commit")
        has(result,"engine retry fixture","production preserves handoff error")
        eq(commits,1,"production Card hook once");eq(kernels,1,"production one common kernel")
        eq(requests,1,"production request once");eq(engine,1,"production failed handoff once")
        local pending=must(plugin._pending_restart_run)
        eq(pending.state,"failed","production retains failed frozen run")
        eq(pending.receipt,actual_receipt,"pending retains real receipt")
        eq(actual_receipt.kind,"SpellHotReload.FileCommit.Receipt","production common receipt kind")
        eq(actual_receipt.changed,true,"production helper genuinely published")
        local snapshot=must(plugin:GetVersions(f.entry.file)).snapshot
        eq(snapshot,actual_receipt.snapshot,"production actual publication installed")
        eq(snapshot.revision,1,"production one revision")
        eq(f.initial.card:init(1),20,"production new helper propagated")
        eq(Anchor.Get(f.entry,"state"),4,"production scalar preserved")
        eq(_handoff_runs,1,"production never replays candidate source")
        must(plugin:Missing(f.entry.file,"handoff fixture"))
        eq(plugin:GetVersions(f.entry.file),nil,"Missing retires public versions lookup")
        eq(plugin._store:GetCandidate(f.entry.file),nil,"Missing cancels candidate")
        eq(plugin._pending_restart_run,pending,"Missing retains exact committed run")
        eq(f.capture.snapshot,snapshot,"Missing retains actual committed snapshot")
        eq(f.entry.reloadable,true,"Missing preserves original first-load verdict")
        eq(f.entry.missing,true,"Missing invalidates this session")
        local can_reload,missing_reason=plugin:_CheckLoad(f.entry.file)
        eq(can_reload,false,"Missing cannot revive first load")
        has(missing_reason,"loaded file missing","Missing keeps reload refusal reason")
        -- Scope traps tightly and restore even if a checked call throws.
        local function retry_without_source()
            local slots={
                {plugin._watcher,"ReadFile"},{Source,"Build"},{Compose,"Create"},
                {plugin._driver,"DiscoverPublished"},{plugin._commit,"Commit"},
                {plugin,"GetVersions"},{Card,"CaptureCurrent"},
            }
            local touched=0
            for _,slot in ipairs(slots) do
                slot[3]=slot[1][slot[2]]
                slot[1][slot[2]]=function() touched=touched+1;error("retry source/publication forbidden") end
            end
            local called,value=pcall(function() return plugin:RetryRestartFromUI() end)
            for _,slot in ipairs(slots) do slot[1][slot[2]]=slot[3] end
            eq(touched,0,"retry does no read/analysis/discovery/publication/selection")
            if not called then error(value,0) end
            return value
        end
        local reads=f.reads
        Restart.Handoff=function() engine=engine+1 end
        result=retry_without_source()
        has(result,"restart requested","production Missing retry success")
        eq(commits,1,"retry never re-registers");eq(kernels,1,"retry never republishes")
        eq(requests,2,"retry uses workflow request");eq(engine,2,"one engine call per attempt")
        eq(f.reads,reads,"retry no disk reads")
        eq(f.capture.snapshot,snapshot,"retry actual version unchanged")
        eq(snapshot.revision,1,"retry revision not advanced")
        eq(plugin._pending_restart_run,nil,"successful retry clears pending")
        eq(plugin._restart_active,false,"retry clears busy")
        eq(pending.state,"accepted","retry only accepts handoff")
        eq(pending.attempts,2,"production two attempts")
        eq(pending.ready,"unobserved","production does not claim Boss readiness")
        eq(legacy,0,"production no legacy publication")

        -- Independent first load: a Missing lifecycle cannot be revived for Apply.
        f=plugin_fixture();plugin=f.plugin
        original=f.initial.card.init;commits,kernels,requests=0,0,0
        kernel=plugin._commit.Commit
        plugin._commit.Commit=function(self,...)
            kernels=kernels+1;return kernel(self,...)
        end
        Restart.Request=function() requests=requests+1;error("refused registration cannot restart") end
        Card.Commit=function()
            commits=commits+1
            return nil,{phase="register",code="ownership",message="adapter refusal fixture"}
        end
        result=plugin:ApplyFromUI()
        has(result,"commit: owner Commit must register its exact tuple once and return true",
            "production Driver reports owner registration contract refusal")
        eq(commits,1,"refusing owner called once");eq(kernels,0,"refusal no common kernel")
        eq(requests,0,"refusal no restart request")
        unchanged(f,original,"production registration refusal")
        eq(plugin._pending_restart_run,nil,"refusal no pending restart")
        local retained=must(plugin._store:GetCandidate(f.entry.file))
        eq(retained.generation,f.candidate.generation,"refusal retains candidate generation")
        eq(retained.first_content,f.candidate.first_content,"refusal retains candidate bytes")
        eq(retained.stable,true,"refusal retains stable candidate")
        eq(legacy,0,"refusal no legacy publication")
    end)
    reset_hooks()
    for _,tx in ipairs(controllers) do tx:Release() end
    for _,plugin in ipairs(plugins) do plugin._watcher=nil;plugin:Release("handoff spec") end
    for _,key in ipairs(modules) do package.loaded[key]=loaded[key] end
    for _,key in ipairs(globals) do rawset(_G,key,saved[key]) end
    if not ok then failed=failed+1;failures[#failures+1]="unexpected: "..(type(problem)=="string" and problem or "opaque error") end
    print(string.format("CardHandoffSpec: %d passed / %d failed",passed,failed))
    for _,label in ipairs(failures) do print("  FAIL "..label) end
    return {passed=passed,failed=failed}
end
return M
