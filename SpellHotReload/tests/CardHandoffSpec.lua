-- Explicit Card transaction/runtime restart handoff. Synthetic first load only; no engine.
-- Lua5.1 plans with a presence fixture, then proves the real kernel refuses join.
local M = {}
local serial = 0
function M.run()
    local Card=require("SpellHotReload.Adapters.Card.Card")
    local Driver=require("SpellHotReload.Pipeline.Driver")
    local Load=require("SpellHotReload.Load.AnchorLoad")
    local Versions=require("SpellHotReload.Adapters.Card.Card")
    local Commit=require("SpellHotReload.Apply.CardCommit")
    local Anchor=require("SpellHotReload.Load.Anchor")
    local Binding=require("SpellHotReload.Adapters.Card.PracticeBinding")
    local Restart=require("SpellHotReload.Runtime.CurrentRestart")
    local Callbacks=require("SpellHotReload.Adapters.Card.CardCallbacks")
    local passed,failed,failures=0,0,{}
    local function check(v,label)
        if v then passed=passed+1 else failed=failed+1;failures[#failures+1]=label end
    end
    local function eq(a,b,label) check(rawequal(a,b),label) end
    local function has(s,p,label) check(type(s)=="string" and s:find(p,1,true)~=nil,label) end
    local function must(v,e) assert(v,type(e)=="table" and e.message or e);return v end
    local function copy(v) local out={};for k,x in next,v do out[k]=x end;return out end
    local function refuse(call,phase,label)
        local called,v,e=pcall(call)
        eq(called,true,label.." no throw")
        if phase=="restart" then check(v~=true,label.." refusal") else eq(v,false,label.." boolean refusal") end
        eq(type(e),"table",label.." structured")
        if type(e)=="table" then
            eq(e.phase,phase,label.." phase");check(type(e.message)=="string",label.." message")
        end
        return e
    end
    local globals={"boss","_editor_class","_tmp_sc","_handoff_runs","jit","lstg"}
    local saved={};for _,key in ipairs(globals) do saved[key]=rawget(_G,key) end
    local join,set=debug.upvaluejoin,debug.setupvalue
    local restart,replay,current=Restart.Handoff,Binding.IsReplay,Binding.CaptureCurrent
    local commit_hook,restart_hook,publish=Card.Commit,Restart.Request,Callbacks.Publish
    local create_hook=require("SpellHotReload.Source.Compose").Create
    local names={"SpellHotReload.Runtime.Plugin","SpellHotReload.Runtime.Watcher","lstg.FileSystemWatcher","lstg.FileSystemWatcher.FileAction"}
    local modules={};for _,key in ipairs(names) do modules[key]=package.loaded[key] end
    local controllers,plugins={},{}
    local defaults={}
    for _,name in ipairs({"before","init","frame","render","beforedel","del","after"}) do
        defaults[name]=function() end
    end
    local function source(n)
        return table.concat({
            "-- Generated by LuaSTG Editor Sharp",
            "local state=4",
            "local function helper(n) return state+n+"..n.." end",
            "_handoff_runs=_handoff_runs+1",
            "_editor_class['K'].cards={}",
            "_tmp_sc=boss.card.New('A',1,2,3,4)",
            "function _tmp_sc:init(n) return helper(n)+10 end",
            "table.insert(_editor_class['K'].cards,_tmp_sc)",
            "_tmp_sc=boss.card.New('B',1,2,3,4)",
            "function _tmp_sc:init(n) return helper(n)+20 end",
            "table.insert(_editor_class['K'].cards,_tmp_sc)",
        },"\n")
    end
    local function fixture()
        serial=serial+1
        debug.setupvalue=set
        debug.upvaluejoin=join or function() error("presence fixture; no shared proof") end
        rawset(_G,"jit",saved.jit)
        _handoff_runs=0;_editor_class={K={}}
        boss={card={_default_card=defaults,New=function(name)
            local c={name=name,is_combat=true};for k,fn in next,defaults do c[k]=fn end;return c
        end}}
        local entry=must(Load.Capture(source(0),{name="Handoff_Boss.lua",
            capability={getupvalue=true,setupvalue=true,upvaluejoin=true}}))
        entry.file="Handoff_Boss.lua"
        local capture=must(Versions.SeedVersions(entry,"handoff:"..serial,_editor_class,defaults))
        local base=capture.snapshot
        local initial={class_key="K",slot=1,name="A",card=_editor_class.K.cards[1],
            names={"A","B"},mode="practice",include_previous=false}
        local live={capture=capture,snapshot=base,entry=entry,classes=_editor_class,
            session_id=base.session_id,content=source(5),binding=initial}
        local driver=Driver.New();assert(driver:RegisterDiscovery(Card))
        local discovery=must(driver:DiscoverPublished(entry.file,live.content,assert(require("SpellHotReload.Adapters.Card.CardVersions").Publication(base)),{session_id=base.session_id,
            registry_entry=entry,loaded_source=base.loaded_source,base_revision=base.revision,
            published_units=base,candidate_generation=3}))
        local fresh=0
        local prepared=must(Card.PrepareVersioned(capture,discovery,initial,live,function()
            fresh=fresh+1;return live
        end))
        return {entry=entry,capture=capture,base=base,initial=initial,live=live,prepared=prepared,
            discovery=discovery,fresh=function() return fresh end}
    end
    local function frozen(f,snapshot)
        local run=Restart.Freeze(f.prepared.target,f.capture)
        if snapshot then assert(Restart.BindReceipt(run,{snapshot=snapshot},f.capture)) end
        local view={session_id=f.base.session_id,entry=f.entry,classes=_editor_class}
        return run,view
    end
    local calls,traps=0,0
    local hostile=setmetatable({}, {__index=function() traps=traps+1;error("hostile index") end,
        __tostring=function() traps=traps+1;error("hostile stringify") end})
    local ok,problem=pcall(function()
        local f=fixture()
        local p,h,ctx=f.prepared,f.prepared.handle,f.prepared.context
        eq(h.context,ctx,"preparation returns same context")
        eq(h.selection,p.selection,"inject freezes output identity")
        eq(ctx.common,f.discovery.snapshot.common,"common never copied or extended")
        eq(ctx.common.transaction,nil,"writer not on common")
        eq(f.discovery.snapshot.by_key["card:K"].context.adapter.transaction,nil,"discovery never extended")
        local original=f.initial.card.init
        local mutation=0
        Callbacks.Publish=function() mutation=mutation+1;error("legacy publish forbidden") end
        refuse(function() return Card.Commit(h,p.selection,ctx) end,"commit","missing transaction")
        ctx.adapter.transaction=function(a,b,c)
            calls=calls+1;eq(a,h,"writer handle");eq(b,p.selection,"writer plan");eq(c,ctx,"writer context")
            return {snapshot=f.base,changed=false}
        end
        local yes,err,receipt=Card.Commit(h,p.selection,ctx)
        eq(yes,true,"success boolean");eq(err,nil,"success error nil");eq(receipt.snapshot,f.base,"receipt forwarded")
        eq(calls,1,"writer called once");eq(mutation,0,"no legacy publication")
        eq(f.initial.card.init,original,"bridge never directly publishes")
        eq(f.capture.snapshot,f.base,"fake receipt not installed by bridge")
        refuse(function() return Card.Commit(h,copy(p.selection),ctx) end,"commit","copied plan")
        local other=copy(ctx)
        refuse(function() return Card.Commit(h,p.selection,other) end,"commit","foreign context")
        refuse(function() return Card.Commit(hostile,p.selection,ctx) end,"commit","hostile handle")
        refuse(function() return Card.Commit(h,hostile,ctx) end,"commit","hostile plan")
        eq(calls,1,"invalid association never enters writer")
        local injected_error={phase="commit",code="rollback",message="kernel refused"}
        ctx.adapter.transaction=function() return nil,injected_error end
        eq(select(2,Card.Commit(h,p.selection,ctx)),injected_error,"kernel failure preserved")
        ctx.adapter.transaction=hostile
        refuse(function() return Card.Commit(h,p.selection,ctx) end,"commit","nonfunction writer")
        ctx.adapter.transaction=nil
        local run,rctx=frozen(f,nil)
        Restart.Handoff=function() calls=calls+1 end
        refuse(function() return Restart.Request(run,rctx) end,"restart","uncommitted run")
        eq(traps,0,"no hostile table callbacks")

        -- Real atomic kernel; the adapter does not invent phase authority.
        f=fixture();p,h,ctx=f.prepared,f.prepared.handle,f.prepared.context
        local controller=must(Commit.New(f.base.session_id));controllers[#controllers+1]=controller
        debug.upvaluejoin=join
        local function writer(token)
            ctx.adapter.transaction=function(a,b,c)
                assert(a==h and b==p.selection and c==ctx)
                return controller:Commit(token,b,f.capture,h.live,h.refresh)
            end
        end
        writer({})
        refuse(function() return Card.Commit(h,p.selection,ctx) end,"commit","foreign token")
        eq(f.capture.snapshot,f.base,"foreign token no version")
        local token_saved,committed_receipt
        local scoped,v,e,got=controller:Run(function(token)
            token_saved=token;writer(token)
            return Card.Commit(h,p.selection,ctx)
        end)
        eq(scoped,true,"trusted scope entered")
        if not join then
            eq(v,false,"real missing join refused");eq(type(e),"table","missing join structured")
            eq(f.capture.snapshot,f.base,"missing join no version")
            eq(f.initial.card.init,f.base.units[f.prepared.target.key].callbacks.init.fn,"missing join no publication")
        else
            eq(v,true,"real kernel commit");eq(e,nil,"real commit no error");check(got.changed,"real changed receipt")
            committed_receipt=got
            eq(f.capture.snapshot,got.snapshot,"actual version installed")
            eq(f.initial.card:init(1),20,"current callback reads new shared helper")
            eq(_editor_class.K.cards[2]:init(1),30,"unselected callback sees shared propagation")
            eq(_editor_class.K.cards[2].init,f.base.units[f.base.order[2]].callbacks.init.fn,"unselected raw wrapper unchanged")
            eq(Anchor.Get(f.entry,"state"),4,"state preserved");eq(_handoff_runs,1,"initialization only once")
            eq(f.fresh(),2,"one locate and one final kernel refresh")
        end
        refuse(function() return Card.Commit(h,p.selection,ctx) end,"commit","expired or committed context")
        local checks,why=controller:Check(token_saved)
        eq(checks,nil,"scope expired");eq(type(why),"table","expired scope structured")
        if join then
            local run,rctx=frozen(f,committed_receipt.snapshot)
            local restarts=0
            Binding.IsReplay=function() return false end
            Restart.Handoff=function(key,name,card,slot)
                restarts=restarts+1;eq(key,"K","frozen class");eq(name,"A","frozen name")
                eq(card,f.initial.card,"frozen card");eq(slot,1,"frozen slot")
            end
            eq(Restart.Request(run,rctx),true,"committed restart")
            f.entry.missing=true;f.entry.reloadable=false
            eq(Restart.Request(run,rctx),true,"Missing retry preserves committed run")
            eq(run.selection,nil,"no candidate plan retained");eq(run.discovery,nil,"no candidate discovery retained")
            eq(run.context,nil,"no transaction context retained")
            refuse(function() return Restart.Request(run,p.selection) end,"restart","retry must not consume plan")
            local wrong=copy(rctx);wrong.session_id="foreign"
            refuse(function() return Restart.Request(run,wrong) end,"restart","foreign restart context")
            Binding.IsReplay=function() return true end
            refuse(function() return Restart.Request(run,rctx) end,"restart","replay retry")
            eq(restarts,1,"accepted request never issued twice")
            Binding.IsReplay=function() return false end
            run,rctx=frozen(f,committed_receipt.snapshot)
            Restart.Handoff=function() error("restart fixture") end
            local _,err=Restart.Request(run,rctx)
            has(err.message,"restart fixture","restart failure structured")
        end

        -- Production Plugin actually invokes the hooks, including Missing retry.
        if join then
            package.loaded[names[3]],package.loaded[names[4]]={},{}
            package.loaded[names[1]],package.loaded[names[2]]=nil,nil
            local Plugin=require("SpellHotReload.Runtime.Plugin")
            f=fixture()
            local plugin=Plugin.New();plugins[#plugins+1]=plugin
            must(plugin:AdoptLoad(f.entry.file,f.entry))
            plugin._activated,plugin._supported,plugin._sandbox_ok=true,true,true
            plugin._watcher={ReadFile=function() return source(5) end}
            plugin._store:SetAccepted(f.entry.file,source(0),"baseline")
            local candidate=plugin._store:BeginCandidate(f.entry.file,3,"handoff")
            must(plugin._store:RecordFirstRead(f.entry.file,candidate.generation,source(5),1))
            must(plugin._store:VerifyStable(f.entry.file,candidate.generation,source(5),2,1))
            Binding.CaptureCurrent=function() return f.initial end
            Binding.IsReplay=function() return false end
            local commits,restarts,engine=0,0,0
            eq(Card.Restart,nil,"production has no adapter restart hook")
            eq(Binding.Restart,nil,"production has no legacy handoff facade")
            Card.Commit=function(h,plan,c)
                commits=commits+1
                eq(h.selection,plan,"production injected identity");eq(h.context,c,"production same context")
                eq(type(c.adapter.transaction),"function","production writer explicit")
                eq(c.common.transaction,nil,"production common read-only")
                local receipt,err=c.adapter.transaction({},plan,c)
                eq(receipt,nil,"bound writer rejects foreign handle")
                eq(err.code,"ownership","bound writer ownership error")
                return commit_hook(h,plan,c)
            end
            Restart.Request=function(run,view)
                restarts=restarts+1
                eq(run.receipt.snapshot,run.snapshot,"production committed receipt")
                eq(view.entry,run.entry,"production frozen lifecycle view")
                eq(plugin._restart_active,true,"busy spans workflow request")
                return restart_hook(run,view)
            end
            Restart.Handoff=function() engine=engine+1;error("engine retry fixture") end
            local result=plugin:ApplyFromUI()
            has(result,"definitions committed; restart failed","production failed restart after commit")
            eq(commits,1,"production commit hook once");eq(restarts,1,"production restart hook once")
            local pending=plugin._pending_restart_run
            check(pending~=nil,"committed frozen run retained")
            local snapshot=plugin:GetVersions(f.entry.file).snapshot
            local create=require("SpellHotReload.Source.Compose").Create
            local discover=plugin._driver.Discover
            local read=plugin._watcher.ReadFile
            plugin._driver.Discover=function() error("retry discovery forbidden") end
            plugin._watcher.ReadFile=function() error("retry disk read forbidden") end
            require("SpellHotReload.Source.Compose").Create=function() error("retry compile forbidden") end
            f.entry.missing=true;f.entry.reloadable=false
            Restart.Handoff=function() engine=engine+1 end
            result=plugin:RetryRestartFromUI()
            require("SpellHotReload.Source.Compose").Create=create
            plugin._driver.Discover=discover;plugin._watcher.ReadFile=read
            has(result,"restart requested","production Missing retry success")
            eq(commits,1,"retry never recommits");eq(restarts,2,"retry uses restart hook")
            eq(engine,2,"one engine call per handoff")
            eq(plugin:GetVersions(f.entry.file).snapshot,snapshot,"retry version not advanced")
            eq(plugin._pending_restart_run,nil,"successful retry clears run")
            eq(plugin._restart_active,false,"success busy cleared")
            f.entry.missing=nil;f.entry.reloadable=true
            -- The first successful definition publication completed this file.
            -- Re-establish an explicit stable generation for the separate
            -- refused-commit check; do not depend on blanket candidate retention.
            candidate=plugin._store:BeginCandidate(f.entry.file,4,"handoff-refusal")
            must(plugin._store:RecordFirstRead(f.entry.file,candidate.generation,source(5),3))
            must(plugin._store:VerifyStable(f.entry.file,candidate.generation,source(5),4,1))
            Card.Commit=function()
                commits=commits+1
                return false,{phase="commit",code="publish",message="adapter refusal fixture"}
            end
            result=plugin:ApplyFromUI()
            has(result,"commit: adapter refusal fixture","production adapter refusal propagated")
            eq(plugin:GetVersions(f.entry.file).snapshot,snapshot,"refused commit no version advance")
            eq(plugin._pending_restart_run,nil,"refused commit creates no retry run")
            eq(restarts,2,"refused commit never enters restart")
        end
    end)
    -- Restore even after unexpected assertion/host failures.
    require("SpellHotReload.Source.Compose").Create=create_hook
    Card.Commit,Restart.Request,Callbacks.Publish=commit_hook,restart_hook,publish
    Restart.Handoff,Binding.IsReplay,Binding.CaptureCurrent=restart,replay,current
    debug.upvaluejoin,debug.setupvalue=join,set
    for _,controller in ipairs(controllers) do controller:Release() end
    for _,plugin in ipairs(plugins) do plugin._watcher=nil;plugin:Release("handoff spec") end
    for _,key in ipairs(names) do package.loaded[key]=modules[key] end
    for _,key in ipairs(globals) do rawset(_G,key,saved[key]) end
    if not ok then failed=failed+1;failures[#failures+1]="unexpected: "..tostring(problem) end
    print(string.format("CardHandoffSpec: %d passed / %d failed",passed,failed))
    for _,label in ipairs(failures) do print("  FAIL "..label) end
    return {passed=passed,failed=failed}
end
return M
