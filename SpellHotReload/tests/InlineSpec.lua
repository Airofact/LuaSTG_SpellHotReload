-- Run from THDiMS/game:
-- luajit plugin/SpellHotReload/SpellHotReload/tests/Run.lua
local M = {}

function M.run()
    local Card = require("SpellHotReload.CardCallbacks")
    local Loader = require("SpellHotReload.GeneratedBossLoader")
    local Registry = require("SpellHotReload.UpvalueRegistry")
    local Binding = require("SpellHotReload.PracticeBinding")
    local saved, keys = {}, { "boss", "task", "_editor_class", "_sc_table", "_tmp_sc", "_other_init", "_boss", "IsValid", "lstg", "stage", "ext", "jit", "MOVE_NORMAL" }
    for _, key in ipairs(keys) do saved[key] = rawget(_G, key) end
    local passed = 0
    local function check(value, message)
        assert(value, message)
        passed = passed + 1
    end
    local ok, err = xpcall(function()
        local constructors, restarts = 0, 0
        local defaults = {}
        for _, name in ipairs({ "before", "init", "frame", "render", "beforedel", "del", "after" }) do
            defaults[name] = function() end
        end
        boss = { card = { _default_card = defaults }, dialog = { New = function() return {} end } }
        MOVE_NORMAL = 1
        boss.move = { New = function() return { name = "", is_sc = false } end }
        boss.card.New = function(name)
            constructors = constructors + 1
            local card = { name = name, is_sc = name ~= "" }
            for key, value in pairs(defaults) do card[key] = value end
            return card
        end
        task = { New = function(self, fn) self.task = coroutine.create(fn) end }
        local function load_source(source)
            _editor_class, _sc_table = {}, {}
            local names = Loader.ListFunctionNames(source)
            return assert((loadstring or load)(source .. "\n" .. Loader.BuildTrailer(names)))()
        end
        local function fixture(version, prefix, init)
            return table.concat({
                "-- Generated by LuaSTG Editor Sharp",
                prefix or "local counter, absent, disabled = 10, nil, false",
                '_editor_class["Boss:Normal"] = {}',
                '_editor_class["Boss:Normal"].cards = {}',
                '_tmp_sc = boss.dialog.New(true)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Normal"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Normal"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("Inline", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:before() counter = counter + 1; self.before_value = counter end',
                'function _tmp_sc:init()',
                init or ('task.New(self, function()\n'
                    .. '  local text = [=[end function _tmp_sc:init()]=]\n'
                    .. '  --[=[ table.insert(_editor_class["Wrong"].cards,_tmp_sc) ]=]\n'
                    .. '  local total = 0\n'
                    .. '  for i=1,3 do if i > 0 then total=total+i end end\n'
                    .. '  repeat total=total-1 until total==3\n'
                    .. '  coroutine.yield()\n'
                    .. '  self.value = total + ' .. version .. '\n'
                    .. '  self.absent, self.disabled = absent, disabled\n'
                    .. 'end)'),
                'end',
                'function _tmp_sc:frame() self.frame_value = ' .. version .. ' end',
                '_tmp_sc.render = function(self) self.render_value = counter end',
                'function _tmp_sc:beforedel() self.beforedel_value = ' .. version .. ' end',
                'function _tmp_sc:del() self.del_value = ' .. version .. ' end',
                'function _tmp_sc:after() self.after_value = ' .. version .. ' end',
                '_tmp_sc.perform=false',
                'table.insert(_editor_class["Boss:Normal"].cards,_tmp_sc)',
                'table.insert(_sc_table,{"Boss:Normal","Inline",_tmp_sc,3,false})',
            }, "\n")
        end
        local old, new = fixture(1), fixture(20)
        local registry = load_source(old)
        local card = _editor_class["Boss:Normal"].cards[3]
        local first_card = _editor_class["Boss:Normal"].cards[2]
        local actor = {}
        card.before(actor)
        local original_render = card.render
        local selected = assert(Card.Select(old, new, "Boss:Normal", 3))
        check(Card.Select(old, new, "Boss:Normal", 1) == nil, "dialog cannot be selected as combat card")
        check(Card.Select(old, new, "Missing", 3) == nil, "missing class rejected")
        local plan = assert(Card.Build(selected, card, new, registry))
        check(actor.task == nil and constructors == 2, "prepare does not run callbacks or constructors")
        Card.Publish(card, plan)
        check(_sc_table[1][3] == card and _editor_class["Boss:Normal"].cards[3] == card, "card identity retained")
        check(_editor_class["Boss:Normal"].cards[2] == first_card, "other card untouched")
        card.init(actor)
        assert(coroutine.resume(actor.task))
        check(actor.value == nil, "nested task still yields")
        assert(coroutine.resume(actor.task))
        check(actor.value == 23, "inline nested task uses new body")
        check(actor.absent == nil and actor.disabled == false, "nil and false captured locals retained")
        card.before(actor)
        card.render(actor)
        check(actor.render_value == 12, "callbacks retain shared local state")
        if debug.upvaluejoin then
            original_render(actor)
            check(actor.render_value == 12, "LuaJIT preserves original upvalue cell")
        end
        card.frame(actor); card.beforedel(actor); card.del(actor); card.after(actor)
        check(actor.frame_value == 20 and actor.beforedel_value == 20
            and actor.del_value == 20 and actor.after_value == 20, "all lifecycle callbacks replaced")

        local no_frame = new:gsub('function _tmp_sc:frame%(%) self.frame_value = 20 end', '')
        Card.Publish(card, assert(Card.Build(assert(Card.Select(old, no_frame, "Boss:Normal", 3)), card, no_frame, registry)))
        check(card.frame == defaults.frame, "deleted frame callback restores default")
        local bad = new:gsub('"Inline", 1', '"Renamed", 1')
        check(Card.Select(old, bad, "Boss:Normal", 3) == nil, "changed card metadata rejected")
        check(Card.Select(old, new .. '\ntable.insert(_editor_class["Boss:Normal"].cards,{})', "Boss:Normal", 3) == nil,
            "inserted slot rejected")
        check(Card.Select(old, new .. '\nthis is not Lua', "Boss:Normal", 3) == nil, "syntax error rejected")
        local unknown = fixture(30, 'local counter, absent, disabled, unknown = 10,nil,false,7', 'self.value=unknown')
        local bad_plan, reason = Card.Build(assert(Card.Select(old, unknown, "Boss:Normal", 3)), card, unknown, registry)
        check(bad_plan == nil and reason:find("uncaptured local", 1, true), "new uncaptured local rejected")
        local before_init = card.init
        local malicious = new .. '\nerror("generated wiring must not run")'
        assert(Card.Build(assert(Card.Select(old, malicious, "Boss:Normal", 3)), card, malicious, registry))
        check(card.init == before_init, "preparation never publishes or executes file wiring")

        -- Named functions and changed wrapper arguments coexist with inline reload.
        local function named(version, argument)
            return fixture(version,
                'local counter, absent, disabled = 10,nil,false\nlocal function pattern(self,n) self.value=n+' .. version .. ' end',
                'pattern(self,' .. argument .. ')')
                .. '\n_other_init = function(self) pattern(self,1) end'
        end
        local old_other = rawget(_G, "_other_init")
        local named_old, named_new = named(1, 1), named(40, 2)
        registry = load_source(named_old)
        card = _editor_class["Boss:Normal"].cards[3]
        local named_plan = assert(Card.Build(assert(Card.Select(named_old, named_new, "Boss:Normal", 3)), card, named_new, registry))
        Card.Publish(card, named_plan)
        card.init(actor)
        check(actor.value == 42, "named body and wrapper arguments updated together")
        _other_init(actor)
        check(actor.value == 41, "shared named-function cell still updates other variants")
        if debug.upvaluejoin then
            for name, fn in pairs(named_plan.functions) do registry[name] = fn end
            local again = named(60, 3)
            Card.Publish(card, assert(Card.Build(assert(Card.Select(named_old, again, "Boss:Normal", 3)), card, again, registry)))
            _other_init(actor)
            check(actor.value == 61, "second reload retains shared-function cell")
        end
        _G._other_init = old_other

        -- Full Plugin transaction with a disk reader and stage restart stand-in.
        local watcher_name = "SpellHotReload.Watcher"
        local saved_watcher = package.loaded[watcher_name]
        if not saved_watcher then package.loaded[watcher_name] = {} end
        local Plugin = require("SpellHotReload.Plugin")
        package.loaded[watcher_name] = saved_watcher
        local p = Plugin.New()
        p._activated, p._supported, p._sandbox_ok = true, true, true
        registry = load_source(old)
        card = _sc_table[1][3]
        p._registry:SetAll("Test_Boss.lua", registry)
        p._registry:SetSource("Test_Boss.lua", old)
        local disk = new
        p._watcher = { ReadFile = function() return disk end }
        lstg = { var = { sc_index = 1 } }
        ext = { replay = { IsReplay = function() return false end } }
        local restart_fails = false
        stage = { group = { PracticeStart = function(name)
            assert(name == "Spell Practice@Spell Practice")
            if restart_fails then error("restart test failure") end
            restarts = restarts + 1
        end } }
        local function candidate_in(file_name, text, stable)
            local c = p._store:BeginCandidate(file_name, 1, "test")
            p._store:RecordFirstRead(file_name, c.generation, text, 2)
            if stable then p._store:VerifyStable(file_name, c.generation, text, 4, 2) end
        end
        local function candidate(text, stable)
            candidate_in("Test_Boss.lua", text, stable)
        end
        candidate(new, false)
        check(not p:Apply():match("^applied"), "first read alone cannot be applied")
        candidate(new, true)
        disk = new .. '\n-- another save'
        check(p:Apply():find("bytes changed", 1, true) ~= nil and restarts == 0, "stale disk rejected")
        disk = new
        ext.replay.IsReplay = function() return true end
        check(p:Apply() == "replay mode not supported", "replay rejected")
        ext.replay.IsReplay = function() return false end
        check(p:Apply():match("^applied") and restarts == 1, "Plugin applies inline callback and restarts")
        check(_sc_table.EXT_POS[3] == card and p._store:GetCandidate("Test_Boss.lua") == nil, "restart binding and candidate commit")
        card.init(actor); assert(coroutine.resume(actor.task)); assert(coroutine.resume(actor.task))
        check(actor.value == 23, "Plugin published new inline body")
        disk = fixture(50)
        candidate(disk, true)
        restart_fails = true
        check(p:Apply():find("definitions committed; restart failed", 1, true) ~= nil and p:HasRestartPending(),
            "restart failure preserves published definitions for retry")
        local committed_init = card.init
        restart_fails = false
        check(p:RetryRestart() == "restarted" and card.init == committed_init and restarts == 2,
            "retry restarts without recompiling")

        -- SC Debugger transaction: start_game output never sets lstg.var.sc_index,
        -- so the class comes from lstg.var._boss_class_name and the current card is
        -- located by identity through the live boss.
        lstg = { var = { _boss_class_name = "Boss:Normal" }, tmpvar = {} }
        registry = load_source(old)
        card = _editor_class["Boss:Normal"].cards[3]
        p._registry:SetAll("Test_Boss.lua", registry)
        p._registry:SetSource("Test_Boss.lua", old)
        local class_cards = _editor_class["Boss:Normal"].cards
        boss.GetCurrentCard = function(b) return b.cards[b.card_num] end
        IsValid = function() return true end

        -- the debug class list no longer contains the live card
        _boss = { cards = { {} }, card_num = 1 }
        disk = fixture(70)
        candidate(disk, true)
        check(p:Apply():find("capture:", 1, true) ~= nil and restarts == 2,
            "unmatched SC Debug card rejected")

        -- dialog / movement slots are real slots but not combat cards
        _boss = { cards = class_cards, card_num = 1 }
        disk = fixture(80)
        candidate(disk, true)
        check(p:Apply():find("card:", 1, true) ~= nil and restarts == 2,
            "non-combat SC Debug slot rejected")

        local debug_init = card.init
        _boss = { cards = class_cards, card_num = 3 }
        disk = fixture(90)
        candidate(disk, true)
        check(p:Apply():match("^applied") and restarts == 3, "Plugin applies from SC Debug and restarts")
        check(_sc_table.EXT_POS[1] == "Boss:Normal" and _sc_table.EXT_POS[3] == card
            and _sc_table.EXT_POS[4] == 3 and _sc_table.EXT_POS[5] == false,
            "SC Debug restart hands off the normal Spell Practice binding")
        check(card.init ~= debug_init, "SC Debug apply published new callbacks")
        card.init(actor); assert(coroutine.resume(actor.task)); assert(coroutine.resume(actor.task))
        check(actor.value == 93, "SC Debug reload published the new inline body")

        -- Generated code may rebuild a class list with `cards={...}`, which
        -- resets the runtime array. Live index 4 is then authored slot 6, so a
        -- live slot must resolve to the descriptor of the rebuilt list.
        local function rebuilt_fixture(version)
            return table.concat({
                "-- Generated by LuaSTG Editor Sharp",
                "local counter, absent, disabled = 10, nil, false",
                '_editor_class["Boss:Rebuilt"] = {}',
                '_editor_class["Boss:Rebuilt"].cards = {}',
                '_tmp_sc = boss.dialog.New(true)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Rebuilt"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("First", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Rebuilt"].cards, _tmp_sc)',
                '_tmp_sc = boss.dialog.New(false)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Rebuilt"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Rebuilt"].cards, _tmp_sc)',
                '_boss_class_name="Boss:Rebuilt" _editor_class["Boss:Rebuilt"].cards={boss.move.New(0,144,60,MOVE_NORMAL),_tmp_sc} _tmp_sc=boss.dialog.New(false)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Rebuilt"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("Second", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:before() counter = counter + 1; self.before_value = counter end',
                'function _tmp_sc:init() self.value = ' .. version
                    .. '; self.absent, self.disabled = absent, disabled end',
                'function _tmp_sc:frame() self.frame_value = ' .. version .. ' end',
                'table.insert(_editor_class["Boss:Rebuilt"].cards, _tmp_sc)',
                'table.insert(_sc_table,{"Boss:Rebuilt","Second",_tmp_sc,#_editor_class["Boss:Rebuilt"].cards,false})',
            }, "\n")
        end
        local rebuilt_old, rebuilt_new = rebuilt_fixture(1), rebuilt_fixture(120)
        local rebuilt_layout = assert(Card.Read(rebuilt_old, "Boss:Rebuilt"))
        check(#rebuilt_layout == 4, "rebuilt class list is read as the live list, not every registration")
        check(rebuilt_layout[1].kind == "move", "inline reset entry keeps its constructor kind")
        local rebuilt_slot = assert(Card.Select(rebuilt_old, rebuilt_new, "Boss:Rebuilt", 4))
        check(rebuilt_slot.constructor:find('"Second"', 1, true) ~= nil,
            "live slot 4 maps to the rebuilt descriptor, not its textual registration index")
        check(Card.Select(rebuilt_old, rebuilt_new, "Boss:Rebuilt", 1) == nil, "inline move slot is not selectable")
        check(Card.Select(rebuilt_old, rebuilt_new, "Boss:Rebuilt", 3) == nil, "rebuilt dialog slot is not selectable")
        check(Card.Select(rebuilt_old, rebuilt_new, "Boss:Rebuilt", 5) == nil, "slot past the live list is rejected")
        check(Card.Select(rebuilt_old, rebuilt_new:gsub('"Second"', '"Renamed"'), "Boss:Rebuilt", 4) == nil,
            "changed rebuilt card metadata rejected")
        check(Card.Select(rebuilt_old, rebuilt_new:gsub("MOVE_NORMAL", "MOVE_DECEL"), "Boss:Rebuilt", 4) == nil,
            "changed inline constructor rejected")

        -- Names: the live class list is never rebuilt, so a rename of the
        -- current card is detected when every other slot still lines up.
        local function live_names(content, key)
            local layout = assert(Card.Read(content, key))
            local names = {}
            for i, entry in ipairs(layout) do names[i] = entry.name or "" end
            return names
        end
        local inline_names = live_names(old, "Boss:Normal")
        check(#inline_names == 3 and inline_names[3] == "Inline", "read exposes literal card names")
        check(inline_names[1] == "" and inline_names[2] == "", "dialogs and non-spell cards read as unnamed")
        local renamed_entry, renamed_reason = Card.Select(old, bad, "Boss:Normal",
            { slot = 3, name = "Inline", names = inline_names })
        check(renamed_entry ~= nil and renamed_entry.name == "Renamed",
            "renamed current card resolves in place: " .. tostring(renamed_reason))
        check(renamed_reason == "renamed in place", "rename reports an in-place match")
        check(Card.Select(old, bad, "Boss:Normal", 3) == nil, "numeric slot still requires an exact layout")
        check(Card.Select(old, new .. '\ntable.insert(_editor_class["Boss:Normal"].cards,{})',
            "Boss:Normal", { slot = 3, name = "Inline", names = inline_names }) ~= nil,
            "an appended card does not disturb a named current card")
        check(Card.Select(old, bad, "Boss:Normal", { slot = 3, name = "Inline" }) ~= nil,
            "rebinding falls back to the loaded layout without a names snapshot")

        -- SC Debug output can place the same card at a different live slot;
        -- the captured name is then the only stable link.
        local function shift_fixture(version, pad, card_name)
            local lines = {
                "-- Generated by LuaSTG Editor Sharp",
                "local counter, absent, disabled = 10, nil, false",
                '_editor_class["Boss:Shift"] = {}',
                '_editor_class["Boss:Shift"].cards = {}',
                '_tmp_sc = boss.dialog.New(true)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Shift"].cards, _tmp_sc)',
            }
            for _ = 1, pad do
                lines[#lines + 1] = '_tmp_sc = boss.card.New("", 1, 2, 3, 100, {}, false)'
                lines[#lines + 1] = 'function _tmp_sc:init() end'
                lines[#lines + 1] = 'table.insert(_editor_class["Boss:Shift"].cards, _tmp_sc)'
            end
            lines[#lines + 1] = '_tmp_sc = boss.card.New("' .. card_name .. '", 1, 2, 3, 100, {}, false)'
            lines[#lines + 1] = 'function _tmp_sc:init() self.value = ' .. version
                .. '; self.absent, self.disabled = absent, disabled end'
            lines[#lines + 1] = 'function _tmp_sc:frame() self.frame_value = ' .. version .. ' end'
            lines[#lines + 1] = 'table.insert(_editor_class["Boss:Shift"].cards, _tmp_sc)'
            return table.concat(lines, "\n")
        end
        local shift_debug = shift_fixture(1, 0, "Shift Spell")
        local shift_full = shift_fixture(200, 1, "Shift Spell")
        local debug_layout = assert(Card.Read(shift_debug, "Boss:Shift"))
        check(#debug_layout == 2 and debug_layout[2].kind == "card" and debug_layout[2].name == "Shift Spell",
            "SC Debug layout keeps the named card at live slot 2")
        check(#assert(Card.Read(shift_full, "Boss:Shift")) == 3, "full package inserts a slot before the card")
        local shifted_entry, shifted_reason = Card.Select(shift_debug, shift_full, "Boss:Shift",
            { slot = 2, name = "Shift Spell", names = live_names(shift_debug, "Boss:Shift") })
        check(shifted_entry ~= nil and shifted_entry.callbacks.init:find("200", 1, true) ~= nil,
            "named card follows its name to the shifted slot: " .. tostring(shifted_reason))
        check(shifted_reason == "name match at slot 3", "shift reports the name-matched slot")
        check(Card.Select(shift_debug, shift_full, "Boss:Shift", 2) == nil,
            "numeric slot rejects the shifted layout")
        check(Card.Select(shift_debug, shift_full:gsub('"Shift Spell"', '"Other"'), "Boss:Shift",
            { slot = 2, name = "Shift Spell", names = live_names(shift_debug, "Boss:Shift") }) == nil,
            "a vanished name is rejected when the layout also shifted")
        local function pair_fixture(first_name, second_name, version)
            return table.concat({
                "-- Generated by LuaSTG Editor Sharp",
                '_editor_class["Boss:Pair"] = {}',
                '_editor_class["Boss:Pair"].cards = {}',
                '_tmp_sc = boss.card.New("' .. first_name .. '", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:init() self.value = ' .. version .. ' end',
                'table.insert(_editor_class["Boss:Pair"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("' .. second_name .. '", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:init() self.value = ' .. version .. ' end',
                'table.insert(_editor_class["Boss:Pair"].cards, _tmp_sc)',
            }, "\n")
        end
        local pair_old = pair_fixture("Alpha", "Beta", 1)
        local pair_renamed = pair_fixture("Gamma", "Delta", 2)
        check(Card.Select(pair_old, pair_renamed, "Boss:Pair",
            { slot = 2, name = "Beta", names = live_names(pair_old, "Boss:Pair") }) == nil,
            "two renamed slots stay ambiguous")
        -- Unnamed non-spell phases carry no name, so index is the only link.
        -- Sharp's SC Debug export keeps the tail of the class list and collapses
        -- the omitted prefix into a movement placeholder, so the live list lines
        -- up with the full package from the end only.
        local function unnamed_fixture(version, debug)
            local lines = {
                "-- Generated by LuaSTG Editor Sharp",
                "local counter, absent, disabled = 10, nil, false",
                '_editor_class["Boss:Unnamed"] = {}',
                '_editor_class["Boss:Unnamed"].cards = {}',
                '_tmp_sc = boss.dialog.New(true)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Unnamed"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:init() self.first = ' .. version .. ' end',
                'table.insert(_editor_class["Boss:Unnamed"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("", 4, 5, 6, 200, {}, false)',
                'function _tmp_sc:before() counter = counter + 1; self.before_value = counter end',
                'function _tmp_sc:init() self.value = ' .. version .. ' end',
                'function _tmp_sc:frame() self.frame_value = ' .. version .. ' end',
                'table.insert(_editor_class["Boss:Unnamed"].cards, _tmp_sc)',
                '_tmp_sc.perform=false',
            }
            if debug then
                lines[#lines + 1] = '_boss_class_name="Boss:Unnamed"'
                    .. ' _editor_class["Boss:Unnamed"].cards={boss.move.New(0,144,60,MOVE_NORMAL),_tmp_sc}'
                    .. ' _tmp_sc=boss.dialog.New(false)'
            else
                lines[#lines + 1] = '_tmp_sc = boss.dialog.New(false)'
            end
            lines[#lines + 1] = 'function _tmp_sc:init() end'
            lines[#lines + 1] = 'table.insert(_editor_class["Boss:Unnamed"].cards, _tmp_sc)'
            lines[#lines + 1] = '_tmp_sc = boss.card.New("Comment Spell", 7, 8, 9, 300, {}, false)'
            lines[#lines + 1] = 'function _tmp_sc:init() self.tail = ' .. version .. ' end'
            lines[#lines + 1] = 'table.insert(_editor_class["Boss:Unnamed"].cards, _tmp_sc)'
            return table.concat(lines, "\n")
        end
        local unnamed_debug, unnamed_full = unnamed_fixture(1, true), unnamed_fixture(200, false)
        local unnamed_live = assert(Card.Read(unnamed_debug, "Boss:Unnamed"))
        check(#unnamed_live == 4 and unnamed_live[1].kind == "move"
            and #assert(Card.Read(unnamed_full, "Boss:Unnamed")) == 5,
            "the debug export keeps the tail of the list behind a movement placeholder")
        local unnamed_entry, unnamed_reason = Card.Select(unnamed_debug, unnamed_full, "Boss:Unnamed",
            { slot = 2, name = "", names = live_names(unnamed_debug, "Boss:Unnamed") })
        check(unnamed_entry ~= nil and unnamed_entry.callbacks.init:find("self.value = 200", 1, true) ~= nil,
            "unnamed slot follows the tail alignment into the full package: " .. tostring(unnamed_reason))
        check(unnamed_reason == "reverse index at slot 3", "tail alignment is reported")
        check(Card.Select(unnamed_debug, unnamed_full, "Boss:Unnamed", 2) == nil,
            "numeric slot still rejects the shifted layout")
        check(Card.Select(unnamed_debug,
            unnamed_full:gsub("boss.dialog.New%(false%)", "boss.dialog.New(true)"),
            "Boss:Unnamed", { slot = 2, name = "", names = live_names(unnamed_debug, "Boss:Unnamed") }) == nil,
            "a changed neighbour slot breaks the alignment and is rejected")

        -- A candidate that only appends phases keeps the head alignment valid.
        local appended = unnamed_full .. "\n" .. table.concat({
            '_tmp_sc = boss.card.New("", 1, 2, 3, 100, {}, false)',
            'function _tmp_sc:init() self.appended = 1 end',
            'table.insert(_editor_class["Boss:Unnamed"].cards, _tmp_sc)',
        }, "\n")
        local appended_entry, appended_reason = Card.Select(unnamed_full, appended, "Boss:Unnamed",
            { slot = 3, name = "", names = live_names(unnamed_full, "Boss:Unnamed") })
        check(appended_entry ~= nil and appended_entry.callbacks.init:find("self.value = 200", 1, true) ~= nil,
            "an appended phase keeps the head alignment: " .. tostring(appended_reason))
        check(appended_reason == "forward index at slot 3", "head alignment is reported")

        -- Identical unnamed lists line up from both ends, so guessing is refused.
        local function plain_fixture(count, debug)
            local lines = {
                "-- Generated by LuaSTG Editor Sharp",
                '_editor_class["Boss:Plain"] = {}',
                '_editor_class["Boss:Plain"].cards = {}',
                '_tmp_sc = boss.card.New("", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:init() end',
            }
            if debug then
                lines[#lines + 1] = '_boss_class_name="Boss:Plain"'
                    .. ' _editor_class["Boss:Plain"].cards={boss.move.New(0,144,60,MOVE_NORMAL),_tmp_sc}'
            else
                lines[#lines + 1] = 'table.insert(_editor_class["Boss:Plain"].cards, _tmp_sc)'
            end
            for _ = 2, count do
                lines[#lines + 1] = '_tmp_sc = boss.card.New("", 1, 2, 3, 100, {}, false)'
                lines[#lines + 1] = 'function _tmp_sc:init() end'
                lines[#lines + 1] = 'table.insert(_editor_class["Boss:Plain"].cards, _tmp_sc)'
            end
            return table.concat(lines, "\n")
        end
        local plain_debug, plain_full = plain_fixture(2, true), plain_fixture(4, false)
        check(#assert(Card.Read(plain_debug, "Boss:Plain")) == 3
            and #assert(Card.Read(plain_full, "Boss:Plain")) == 4,
            "identical unnamed lists differ only in length")
        local _, plain_reason = Card.Select(plain_debug, plain_full, "Boss:Plain",
            { slot = 2, name = "", names = live_names(plain_debug, "Boss:Plain") })
        check(plain_reason ~= nil and plain_reason:find("both ends", 1, true) ~= nil,
            "unnamed slots that line up from both ends stay ambiguous: " .. tostring(plain_reason))

        registry = load_source(rebuilt_old)
        local rebuilt_cards = _editor_class["Boss:Rebuilt"].cards
        check(#rebuilt_cards == 4 and rebuilt_cards[4].name == "Second", "reset replaced the live class list")
        lstg = { var = { sc_index = 1 }, tmpvar = {} }
        local practice_current = assert(Binding.CaptureCurrent())
        check(practice_current.mode == "practice" and practice_current.slot == 4,
            "practice capture keeps the engine's live slot")
        check(assert(Card.Select(rebuilt_old, rebuilt_new, "Boss:Rebuilt", practice_current.slot))
            .constructor:find('"Second"', 1, true) ~= nil,
            "practice live slot maps to the rebuilt descriptor")

        lstg = { var = { _boss_class_name = "Boss:Rebuilt" }, tmpvar = {} }
        _boss = { cards = rebuilt_cards, card_num = 4 }
        local rebuilt_card = rebuilt_cards[4]
        p._registry:SetAll("Rebuilt_Boss.lua", registry)
        p._registry:SetSource("Rebuilt_Boss.lua", rebuilt_old)
        disk = rebuilt_new
        candidate_in("Rebuilt_Boss.lua", disk, true)
        local rebuilt_result = p:Apply()
        check(rebuilt_result:match("^applied") and restarts == 4,
            "Plugin applies from a rebuilt SC Debug list: " .. tostring(rebuilt_result))
        check(_sc_table.EXT_POS[1] == "Boss:Rebuilt" and _sc_table.EXT_POS[3] == rebuilt_card
            and _sc_table.EXT_POS[4] == 4 and _sc_table.EXT_POS[5] == false,
            "rebuilt list hands off the live slot to normal Spell Practice")
        rebuilt_card.init(actor)
        check(actor.value == 120 and actor.absent == nil and actor.disabled == false,
            "rebuilt list published the matched card's new body")

        -- Renaming the current card keeps the reload on the live card object and
        -- refreshes the handoff name so later captures match directly.
        p._registry:SetAll("Rebuilt_Boss.lua", registry)
        p._registry:SetSource("Rebuilt_Boss.lua", rebuilt_old)
        disk = rebuilt_new:gsub('"Second"', '"Renamed"')
        candidate_in("Rebuilt_Boss.lua", disk, true)
        local rename_result = p:Apply()
        check(rename_result:match("^applied") and restarts == 5,
            "Plugin applies an in-place rename: " .. tostring(rename_result))
        check(rename_result:find("renamed in place", 1, true) ~= nil, "rename reason is reported")
        check(_sc_table.EXT_POS[1] == "Boss:Rebuilt" and _sc_table.EXT_POS[3] == rebuilt_card
            and _sc_table.EXT_POS[4] == 4 and _sc_table.EXT_POS[2] == "Renamed",
            "rename refreshes the handoff name")
        local refreshed = assert(Binding.CaptureCurrent())
        check(refreshed.name == "Renamed" and refreshed.slot == 4, "capture returns the refreshed name")
        check(refreshed.names[4] == "Second", "live snapshot still describes the running list")
        rebuilt_card.init(actor)
        check(actor.value == 120, "renamed card keeps its matched new body")

        -- SC Debug -> full package: the same card sits at a different live slot,
        -- so only the captured name can select the descriptor to compile.
        p._registry:SetSource("Shift_Boss.lua", shift_debug)
        local shift_live = load_source(shift_debug)
        p._registry:SetAll("Shift_Boss.lua", shift_live)
        local shift_cards = _editor_class["Boss:Shift"].cards
        lstg = { var = { _boss_class_name = "Boss:Shift" }, tmpvar = {} }
        _boss = { cards = shift_cards, card_num = 2 }
        local shift_card = shift_cards[2]
        disk = shift_full
        candidate_in("Shift_Boss.lua", disk, true)
        local shift_result = p:Apply()
        check(shift_result:match("^applied") and restarts == 6,
            "Plugin applies across a shifted layout: " .. tostring(shift_result))
        check(shift_result:find("name match at slot 3", 1, true) ~= nil, "shift match reason is reported")
        check(_sc_table.EXT_POS[3] == shift_card and _sc_table.EXT_POS[4] == 2,
            "shifted reload keeps the live card and its restart slot")
        shift_card.init(actor)
        check(actor.value == 200 and actor.absent == nil and actor.disabled == false,
            "shifted reload published the matched body")
        shift_card.frame(actor)
        check(actor.frame_value == 200, "shifted reload published the matched frame")
        check(#shift_cards == 2 and shift_cards[2] == shift_card, "the live class list is not rebuilt")

        -- End to end: an unnamed non-spell card reached through SC Debug keeps
        -- its reload binding once the game is repacked as a normal full package.
        lstg = { var = { _boss_class_name = "Boss:Unnamed" }, tmpvar = {} }
        p._registry:SetAll("Unnamed_Boss.lua", load_source(unnamed_debug))
        p._registry:SetSource("Unnamed_Boss.lua", unnamed_debug)
        local unnamed_cards = _editor_class["Boss:Unnamed"].cards
        _boss = { cards = unnamed_cards, card_num = 2 }
        local unnamed_card = unnamed_cards[2]
        disk = unnamed_full
        candidate_in("Unnamed_Boss.lua", disk, true)
        local unnamed_result = p:Apply()
        check(unnamed_result:match("^applied") and restarts == 7,
            "Plugin applies to an unnamed non-spell card across the Debug/full shift: "
                .. tostring(unnamed_result))
        check(unnamed_result:find("reverse index at slot 3", 1, true) ~= nil, "tail alignment reason is reported")
        check(_sc_table.EXT_POS[3] == unnamed_card and _sc_table.EXT_POS[4] == 2,
            "unnamed reload keeps the live card and its restart slot")
        unnamed_card.init(actor)
        check(actor.value == 200, "unnamed reload published the matched body")
        unnamed_card.frame(actor)
        check(actor.frame_value == 200, "unnamed reload published the matched frame")
    end, debug.traceback)
    for _, key in ipairs(keys) do _G[key] = saved[key] end
    if not ok then error(err, 0) end
    print(string.format("[SpellHotReload inline tests] %d passed", passed))
    return { passed = passed, failed = 0 }
end

