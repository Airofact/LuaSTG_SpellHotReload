-- Opt-in real-engine smoke. Load from the startup macro before lib/Lplugin.lua.
-- Creates only userdata/spell_hot_reload_smoke/*; never edits mod/project files.
local output_root = "userdata/spell_hot_reload_smoke"
local file_name = "InlineSmoke_Boss.lua"
local class_key = "__SpellHotReloadSmoke:Normal"
local finished = false

local function finish(ok, message)
    if finished then return end
    finished = true
    local text = (ok and "PASS " or "FAIL ") .. tostring(message)
    lstg.Log(ok and 2 or 4, "[SpellHotReload engine smoke] " .. text)
    local f = assert(io.open(output_root .. "/result.txt", "wb"))
    f:write(text, "\n"); f:close()
    lstg.quit_flag = true
end

local function install()
    lstg.FileManager.CreateDirectory(output_root)
    local source = [=[-- Generated by LuaSTG Editor Sharp
local counter = 10
__shr_smoke.wiring = __shr_smoke.wiring + 1
_editor_class["__SpellHotReloadSmoke:Normal"] = Class(_editor_class["DIMS_4B_Boss:Normal"])
_editor_class["__SpellHotReloadSmoke:Normal"].cards = {}
_editor_class["__SpellHotReloadSmoke:Normal"].name = "Inline Reload Smoke"
_editor_class["__SpellHotReloadSmoke:Normal"].difficulty = "Normal"
_editor_class["__SpellHotReloadSmoke:Normal"].bgm = "bgm:stage3_boss_bgm"
_tmp_sc = boss.card.New("Inline Reload Smoke", 0, 1, 60, 999999, {0,0,0}, false)
function _tmp_sc:before()
    counter = counter + 1
    self._shr_counter = counter
end
function _tmp_sc:init()
    self._shr_version = SMOKE_VERSION
    __shr_smoke.boss = self
    task.New(self, function()
        task.Wait(2)
        local total = 0
        for i = 1, 3 do
            if i > 0 then total = total + i end
        end
        self._shr_task = total + SMOKE_VERSION
    end)
end
function _tmp_sc:frame() self._shr_frame = SMOKE_VERSION end
function _tmp_sc:render() self._shr_render = SMOKE_VERSION end
function _tmp_sc:beforedel() end
function _tmp_sc:del() end
function _tmp_sc:after() end
_tmp_sc.perform = false
table.insert(_editor_class["__SpellHotReloadSmoke:Normal"].cards, _tmp_sc)
table.insert(_sc_table, {"__SpellHotReloadSmoke:Normal", "Inline Reload Smoke", _tmp_sc, 1, false})
]=]
    local function write_version(version)
        local f = assert(io.open(output_root .. "/" .. file_name, "wb"))
        f:write((source:gsub("SMOKE_VERSION", tostring(version))))
        f:close()
    end
    __shr_smoke = { wiring = 0 }
    write_version(1)
    -- The production DoFile hook must capture both functions and the loaded source.
    lstg.DoFile(output_root .. "/" .. file_name)
    local live = require("SpellHotReload.View").plugin
    assert(live and live:GetRegistry():GetSource(file_name), "production load hook did not capture source")
    local Plugin = require("SpellHotReload.Plugin")
    local Watcher = require("SpellHotReload.Watcher")
    local Binding = require("SpellHotReload.PracticeBinding")
    local p = Plugin.New()
    p._registry = live:GetRegistry()
    p._activated, p._supported, p._sandbox_ok = true, true, true
    p._root = output_root
    p._watcher = Watcher.New({ root = output_root, store = p:GetStore(), quiet_frames = 3 })
    p._watcher:baseline()
    assert(p._watcher:Start())
    local card = _editor_class[class_key].cards[1]
    local class_count, spell_count = #all_class, #_sc_table
    local frames, phase, old_boss = 0, "start", nil
    local dismiss_frame, rescan_frame = 0, 0
    local version = 1
    local view = {}
    function view:getWindowName() return "SpellHotReload engine smoke" end
    function view:getMenuGroupName() return "Tool" end
    function view:getEnable() return false end
    function view:setEnable() end
    function view:layout() end
    function view:update()
        if finished then return end
        local ok, err = xpcall(function()
            frames = frames + 1
            assert(frames < 1800, "timed out in phase " .. phase)
            p:Tick()
            if phase == "start" and frames > 5 then
                lstg.var.player_name = player_list[1][2]
                lstg.var.rep_player = player_list[1][3]
                Binding.Restart(class_key, card.name, card, 1, false)
                phase = "running"
            elseif phase == "running" then
                local actor = __shr_smoke.boss
                if actor and IsValid(actor) and actor._shr_task == 6 + version and actor._shr_render == version then
                    assert(actor._shr_version == version and actor._shr_frame == version, "callback version mismatch")
                    assert(actor._shr_counter == 10 + version, "captured local state was reset")
                    if old_boss then assert(actor ~= old_boss and not IsValid(old_boss), "restart did not replace Boss") end
                    assert(__shr_smoke.wiring == 1 and #all_class == class_count and #_sc_table == spell_count,
                        "generated wiring or class registration was repeated")
                    -- the fourth edit is never applied: it only covers Dismiss
                    old_boss = actor
                    version = version + 1
                    write_version(version)
                    phase = "candidate"
                end
            elseif phase == "candidate" then
                local candidate = p:GetStore():GetCandidate(file_name)
                if candidate and candidate.stable then
                    if version >= 4 then
                        -- regression: bytes the user rejected must not be re-promoted
                        -- by the periodic drift scan
                        p:Dismiss(file_name)
                        assert(p:GetStore():GetCandidate(file_name) == nil, "dismiss did not clear the candidate")
                        dismiss_frame = frames
                        phase = "dismissed"
                    else
                        local result = p:Apply()
                        assert(result:match("^applied"), result)
                        assert(_editor_class[class_key].cards[1] == card, "live card identity changed")
                        phase = "running"
                    end
                end
            elseif phase == "dismissed" then
                -- default drift interval is 120 frames; allow a full interval plus the
                -- quiet window and read gap before declaring the rejection durable
                if frames - dismiss_frame > 180 then
                    assert(p:GetStore():GetCandidate(file_name) == nil,
                        "dismissed candidate came back after the drift scan")
                    p:Rescan()
                    rescan_frame = frames
                    phase = "rescan"
                end
            elseif phase == "rescan" then
                if frames - rescan_frame > 30 then
                    assert(p:GetStore():GetCandidate(file_name) == nil, "rescan resurrected a dismissed candidate")
                    p:StopWatching()
                    finish(true, "real watcher + two fresh practice restarts + Dismiss durable across drift/rescan")
                end
            end
        end, debug.traceback)
        if not ok then p:StopWatching(); finish(false, err) end
    end
    require("lib.Ldebug").addView("spellHotReload.engineSmoke", view)
end

-- Chain the startup loader; register after the plugin manager exists.
local original = lstg.DoFile
lstg.DoFile = function(filename, ...)
    local result = original(filename, ...)
    if filename:gsub("\\", "/"):match("lib/Lplugin%.lua$") then
        lstg.plugin.RegisterEvent("afterMod", "spellHotReload.engineSmoke", 1000, function()
            local ok, err = xpcall(install, debug.traceback)
            if not ok then finish(false, err) end
        end)
    end
    return result
end
