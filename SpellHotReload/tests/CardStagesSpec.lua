    end
    local function phase(unit,ctx)
        if ctx.scope=="unit" then return ctx.phase=="locate" and "locate" or "unit" end
        return ctx.phase=="resolve" and "constraints" or "prepare"
    end
    -- Observe the REAL Driver-created arguments; each injected case delegates the
    -- actual hook once, leaving Driver/Dependencies error normalization intact.
    local function run(f,which,change,production)
        local locate,inject=Card.Locate,Card.Inject
        local function dispatch(h,u,c)
            local label=phase(u,c);local row={handle=h,unit=u,context=c}
            f.events[#f.events+1]=label;f.stages[label]=row
            if label==which then
                f.hits=(f.hits or 0)+1;h,u,c=change(f,h,u,c)
            end
            local v,e
            if label=="locate" then v,e=locate(u,c) else v,e=inject(h,u,c) end
            row.value,row.error=v,e
            if label==which then f.direct=v;f.error=e end
            return v,e
        end
        local value,err
        local rows={{Card,"Locate",function(u,c) return dispatch(nil,u,c) end},
            {Card,"Inject",function(h,u,c) return dispatch(h,u,c) end}}
        if production then
            local operation=f.p._VersionedOperation
            rows[#rows+1]={f.p,"_VersionedOperation",function(self,...)
                local op,live,refresh=operation(self,...);f.op=op;return op,live,refresh
            end}
        end
        patched(rows,function()
            if production then value,err=f.p:_PrepareVersioned(f.entry.file,f.candidate,f.capture,f.discovery,f.initial,"current")
            else value,err=FileApply.Prepare(f.p._driver,f.discovery,f.op) end
        end)
        return value,err
    end
    local function case(label,which,change,expected,code)
        local f=fixture();local v,e=run(f,which,change)
        eq(f.hits,1,label.." exact stage reached once")
        refusal(f.direct,f.error,expected,label.." direct",code)
        refusal(v,e,expected,label.." pipeline",code);eq(e,f.error,label.." structured identity retained")
        eq(f.stages.prepare==nil or which=="prepare",true,label.." no later final preparation")
        unchanged(f,label);return f,e
    end
    local ok,problem=pcall(function()
        must(Anchor.Supported(Compose.Capability(debug)))
        eq(Callbacks.Publish,nil,"retired publication export absent")
        local f=fixture();local prepared=must(run(f))
        eq(#prepared.dependencies.safe_roots,1,"real Current root safe")
        eq(#prepared.dependencies.blocked_roots,0,"real Current root not silently blocked")
        local snap=f.discovery.snapshot;local located=f.stages.locate;local resolved=f.stages.unit
