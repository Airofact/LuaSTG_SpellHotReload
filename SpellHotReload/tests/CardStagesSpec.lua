        eq(ctx.operation,f.op,"explicit operation");eq(ctx.view,handle.view,"original view")
        eq(ctx.base_group,handle.view.base_group,"actual original Card group")
        eq(ctx.adapter.runtime,nil,"no legacy runtime bridge")
