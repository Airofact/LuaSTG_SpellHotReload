-- Read-only version/action/pending presentation fixtures. Only synthetic first-load chunks
-- execute; candidate top-level, card construction, and callback bodies never do.
-- Lua5.1 checks real missing-join refusal; only LuaJIT performs shared commits.
local M = {}
function M.run()
    local globals={"lstg","boss","_editor_class","_tmp_sc","_sc_table","ext","_va_runs","_va_api","jit","IsValid"}
    local saved={}
    for _,name in ipairs(globals) do saved[name]=rawget(_G,name) end
    local modules={"lstg.FileSystemWatcher","lstg.FileSystemWatcher.FileAction","SpellHotReload.Watcher","SpellHotReload.Plugin","imgui","SpellHotReload.UI.Tab.MonitorTab"}
    local loaded={}
    for _,name in ipairs(modules) do loaded[name]=package.loaded[name] end
    package.loaded[modules[1]]={}
    package.loaded[modules[2]]={}
    package.loaded[modules[3]]=nil;package.loaded[modules[4]]=nil
    local Plugin=require("SpellHotReload.Plugin")
    local Load=require("SpellHotReload.Load.AnchorLoad")
    local Anchor=require("SpellHotReload.Load.Anchor")
    local Binding=require("SpellHotReload.Adapters.Card.PracticeBinding")
    local Compose=require("SpellHotReload.Source.Compose")
    local Card=require("SpellHotReload.Adapters.Card.Card")
    local passed,failed,failures=0,0,{}
    local function check(v,label)
        if v then passed=passed+1 else failed=failed+1;failures[#failures+1]=label end
    end
    local function eq(a,b,label) check(a==b,label.." expected "..tostring(b)..", got "..tostring(a)) end
    local function has(s,p,label) check(type(s)=="string" and s:find(p,1,true)~=nil,label.." ("..tostring(s)..")") end
    local function must(v,err) assert(v,type(err)=="table" and err.message or err);return v end
    local get,set,join=debug.getupvalue,debug.setupvalue,debug.upvaluejoin
    local old_restart,old_plan,old_create=Binding.Restart,Card.Plan,Compose.Create
    local plugins,current={},nil
    local callbacks={"before","init","frame","render","beforedel","del","after"}
    local defaults={}
    for _,name in ipairs(callbacks) do defaults[name]=function() return "default" end end
    local FILE="Inspect_Boss.lua"
    local SIDE=table.concat({
        "_editor_class['L'].cards={}",
        "_tmp_sc=boss.card.New('C',1,2,3,100)",
        "function _tmp_sc:init(n) return helper(n)+300 end",
        "table.insert(_editor_class['L'].cards,_tmp_sc)",
    },"\n")
    local SOURCE=table.concat({
        "-- Generated by LuaSTG Editor Sharp",
        "local state=4",
        "local function helper(n) return state+n end",
        "local function idle(n) return n+1000 end",
        "local function setstate(v) state=v end",
        "_va_runs=_va_runs+1","_va_api={set=setstate}",
        "_editor_class['K'].cards={boss.move.New(0,0,1)}",
        "_tmp_sc=boss.card.New('A',1,2,3,100)",
        "function _tmp_sc:init(n) return helper(n) end",
        "table.insert(_editor_class['K'].cards,_tmp_sc)",
        "_tmp_sc=boss.card.New('B',1,2,3,100)",
        "function _tmp_sc:init(n) return helper(n)+100 end",
        "table.insert(_editor_class['K'].cards,_tmp_sc)",
        SIDE,
    },"\n")
    local EDIT=SOURCE:gsub("state=4","state=999"):gsub("state%+n end","state+n+10 end")
        :gsub("n%+1000","n+2000"):gsub("helper%(n%)%+100","helper(n)+200")
    local function enter(f,slot,mode)
        slot=slot or 2
        _sc_table[1]={"K",f.classes.K.cards[slot].name,f.classes.K.cards[slot],slot,false}
        lstg.var.sc_index=1
        f.mode=mode or "practice"
    end
    local function candidate(f,content)
        f.disk=content
        local c=f.p._store:BeginCandidate(FILE,f.p._store._next_generation,"spec")
        must(f.p._store:RecordFirstRead(FILE,c.generation,content,1))
        return must(f.p._store:VerifyStable(FILE,c.generation,content,2,1))
    end
    local function fixture()
        Compose.Create=old_create
        debug.getupvalue,debug.setupvalue,debug.upvaluejoin=get,set,join
        _G.jit=saved.jit
        _va_runs=0
        _G.IsValid=function() return true end
        _editor_class={K={},L={}}
        _sc_table={}
        ext={replay={IsReplay=function() return current and current.replay==true end}}
        lstg={var={},Log=function() end,FileManager={EnumFiles=function() return {{FILE,false}} end}}
        local f={constructions=0,restarts=0,reads=0,discoveries=0,creates=0,legacy=0,classes=_editor_class}
        current=f
        boss={card={_default_card=defaults,New=function(name)
            f.constructions=f.constructions+1
            local c={name=name,is_combat=true}
            for _,cb in ipairs(callbacks) do c[cb]=defaults[cb] end
            return c
        end},move={New=function() return {is_combat=false} end}}
        f.p=Plugin.New();plugins[#plugins+1]=f.p
        f.entry=must(Load.Capture(SOURCE,{name=FILE}))
        must(f.p:AdoptLoad(FILE,f.entry))
        f.capture=f.p:GetVersions(FILE)
        f.p._activated,f.p._supported=true,true
        f.p._activation_attempted=true
        f.p._sandbox_ok=join~=nil
        f.p._sandbox_error="shared-cell debug APIs unavailable"
        f.disk=EDIT
        f.p._store:SetAccepted(FILE,SOURCE,"baseline")
        local Watcher=require("SpellHotReload.Watcher")
        f.p._watcher=Watcher.New({root="mod/Test",store=f.p._store,quiet_frames=1,read_gap=1,drift_interval=5})
        f.p._watcher.ReadFile=function()
            f.reads=f.reads+1
            if f.on_read then f.on_read(f) end
            return f.disk
        end
        candidate(f,EDIT)
        enter(f,2)
        local driver=f.p._driver
        local discover=driver.Discover
        driver.Discover=function(self,...)
            f.discoveries=f.discoveries+1
            if f.on_discover then f.on_discover(f) end
            return discover(self,...)
        end
        local function legacy() f.legacy=f.legacy+1;error("legacy publication forbidden") end
        driver.Commit,driver.Restart,f.p._Publish,f.p._registry.SetAll,f.p._anchors.SetAll=legacy,legacy,legacy,legacy,legacy
        Card.Plan=legacy
        Binding.Restart=function(class_key,name,card,slot,include_previous)
            f.restarts=f.restarts+1
            f.restart_args={class_key,name,card,slot,include_previous}
            if f.on_restart then f.on_restart(f) end
            _sc_table.EXT_POS={class_key,name,card,slot,include_previous}
            lstg.var.sc_index="EXT_POS"
        end
        Compose.Create=function(...)
            f.creates=f.creates+1
            if f.on_create then f.on_create(f) end
            return old_create(...)
        end
        return f
    end
    local function row(rows,key)
        for _,r in ipairs(rows) do if r.key==key then return r end end
        error("missing display row "..key)
    end
    local function scalar_tree(value)
        if type(value)~="table" then return type(value)=="string" or type(value)=="number" or type(value)=="boolean" end
        if getmetatable(value) then return false end
        for k,v in next,value do
            if (type(k)~="string" and type(k)~="number") or not scalar_tree(v) then return false end
        end
        return true
    end
    local function unchanged(f,base,label)
        eq(f.capture.snapshot,base,label.." publication snapshot")
        eq(Anchor.Get(f.entry,"helper"),base.functions.units.helper.fn,label.." helper cell")
        for _,key in ipairs(base.order) do
            local u=base.units[key]
            for _,cb in ipairs(callbacks) do eq(u.card[cb],u.callbacks[cb].fn,label.." callback "..key..cb) end
        end
        eq(f.p._store:HasPartialPublication(FILE),false,label.." no partial record")
        eq(f.restarts,0,label.." no restart")
        eq(_va_runs,1,label.." no top-level replay")
        eq(f.constructions,3,label.." no constructors")
        eq(f.legacy,0,label.." no legacy fallback")
    end
    local old_describe=require("SpellHotReload.Adapters.Card.CardVersions").Describe
    local ok,problem=pcall(function()
        local f=fixture()
        eq(f.p:InspectCandidate(nil),nil,"invalid file refused")
        local Cards=require("SpellHotReload.Adapters.Card.CardVersions")
        local v,e=Cards.Describe(nil)
        eq(v,nil,"invalid description refused");eq(e.code,"unsupported","invalid description reason")
        if not join then
            v,e=f.p:InspectCandidate(FILE)
            eq(v,nil,"real missing join no manufactured preview")
            has(e,"patch capability unavailable","missing join diagnostic")
            eq(f.discoveries,0,"missing join no discovery")
            eq(f.p:GetCandidateInspection(FILE,Binding.CaptureCurrent()),nil,"missing join no cache")
            eq(f.restarts,0,"missing join no restart")
            print("MonitorVersionsSpec: real shared preview not run (Lua5.1 missing join)")
        else
            local base=f.capture.snapshot
            local joins,writes,flushes=0,0,0
            local flush=saved.jit and saved.jit.flush
            debug.upvaluejoin=function(...) joins=joins+1;return join(...) end
            debug.setupvalue=function(...) writes=writes+1;return set(...) end
            if flush then jit.flush=function(...) flushes=flushes+1;return flush(...) end end
            local model=must(f.p:InspectCandidate(FILE))
            debug.upvaluejoin,debug.setupvalue=join,set
            if flush then jit.flush=flush end
            eq(joins,0,"inspection no joins");eq(writes,0,"inspection no writes");eq(flushes,0,"inspection no flush")
            unchanged(f,base,"inspection")
            eq(model.revision,0,"published revision not proposed revision")
            eq(model.generation,f.p._store:GetCandidate(FILE).generation,"exact inspected generation")
            eq(model.target.live_slot,2,"live restart slot separate")
            eq(model.target.source_slot,2,"candidate source slot separate")
            eq(model.target.name,"A","live metadata unchanged")
            eq(#model.cards,3,"all cards, not filtered current-only")
            eq(#model.functions,3,"all local functions")
            eq(row(model.functions,"local:helper").selected,true,"helper selected")
            eq(row(model.functions,"local:helper").definition_version,1,"helper actual published v1")
            eq(row(model.functions,"local:idle").pending,true,"independent function pending")
            eq(row(model.cards,"card:1:K:2").action,"shared-impact","helper-only root no wrapper publish")
            eq(row(model.cards,"card:1:K:3").pending,true,"other edited wrapper pending")
            eq(row(model.cards,"card:1:K:3").affected,true,"old sibling sees selected shared helper")
            eq(model.initializers[1].name,"state","initializer diagnostic")
            eq(model.initializers[1].requires_restart,true,"initializer restart required")
            check(scalar_tree(model),"detached scalar-only description")
            model.cards[1].definition_version=999
            model.initializers[1].name="corrupted"
            local cached=must(f.p:GetCandidateInspection(FILE,Binding.CaptureCurrent()))
            eq(cached.cards[1].definition_version,1,"returned inspection cannot mutate cache")
            eq(cached.initializers[1].name,"state","nested cache detached")
            cached.functions[1].action="corrupted"
            local reads,discovery_count,creates=f.reads,f.discoveries,f.creates
            for i=1,25 do
                cached=must(f.p:GetCandidateInspection(FILE,Binding.CaptureCurrent()))
                check(cached.functions[1].action~="corrupted","getter copy "..i)
            end
            eq(f.reads,reads,"cached display no disk read")
            eq(f.discoveries,discovery_count,"cached display no Match")
            eq(f.creates,creates,"cached display no compile")
            unchanged(f,base,"cached display")

            has(f.p:ApplyFromUI(),"applied","Apply still owns production commit")
            eq(f.capture.snapshot.revision,1,"one actual commit")
            eq(f.p:GetCandidateInspection(FILE,Binding.CaptureCurrent()),nil,"Apply invalidates inspection")
            enter(f,2)
            model=must(f.p:InspectCandidate(FILE))
            eq(model.revision,1,"inspect actual published r1")
            eq(row(model.functions,"local:helper").definition_version,2,"published helper v2")
            eq(row(model.cards,"card:1:K:3").definition_version,1,"pending wrapper keeps source v1")
            eq(row(model.cards,"card:1:K:3").observed[1].version,2,"published observation advances alone")
            eq(row(model.cards,"card:1:K:3").pending,true,"pending wrapper not swallowed")
            eq(row(model.functions,"local:idle").pending,true,"pending local retained")
            eq(row(model.cards,"card:1:K:3").affected,false,"no fictional repeated propagation")
            eq(f.p._store:GetPartialPublication(FILE).revision,1,"partial ledger separate")
            local after=f.capture.snapshot
            f.p:Dismiss(FILE)
            eq(f.p:GetCandidateInspection(FILE,Binding.CaptureCurrent()),nil,"Dismiss clears display")
            eq(f.capture.snapshot,after,"Dismiss no version ACK")
            eq(f.p._store:HasPartialPublication(FILE),true,"Dismiss keeps partial")
            eq(f.p:InspectCandidate(FILE),nil,"dismissed bytes no current inspection")

            local cases={"bytes","generation","binding","names","class","list","capture","snapshot","missing","replay","publication","poison","release"}
            for _,fault in ipairs(cases) do
                f=fixture();must(f.p:InspectCandidate(FILE))
                local reads_before,creates_before=f.reads,f.creates
                local binding=Binding.CaptureCurrent()
                if fault=="bytes" then
                    local c=f.p._store._candidates[FILE];c.first_content=EDIT.."\n-- changed";c.first_hash="collision"
                elseif fault=="generation" then candidate(f,EDIT)
                elseif fault=="binding" then enter(f,3);binding=Binding.CaptureCurrent()
                elseif fault=="names" then binding.names[3]="renamed"
                elseif fault=="class" then _editor_class.K={}
                elseif fault=="list" then _editor_class.K.cards={}
                elseif fault=="capture" then f.p._versions[FILE]={capture={snapshot=f.capture.snapshot}}
                elseif fault=="snapshot" then f.capture.snapshot={}
                elseif fault=="missing" then f.entry.missing=true;f.entry.reloadable=false
                elseif fault=="replay" then f.replay=true
                elseif fault=="publication" then f.p._publication_error="restart game"
                elseif fault=="poison" then f.p._commit.Poisoned=function() return true end
                elseif fault=="release" then f.p:Release() end
                eq(f.p:GetCandidateInspection(FILE,binding),nil,fault.." cached inspection invalidated")
                eq(next(f.p._candidate_inspections),nil,fault.." cached strong references dropped")
                eq(f.reads,reads_before,fault.." getter no disk")
                eq(f.creates,creates_before,fault.." getter no compile")
            end

            for _,fault in ipairs({"disk","generation","binding","throw"}) do
                f=fixture();local before=f.capture.snapshot
                f.on_discover=function()
                    if fault=="disk" then f.disk=EDIT.."\n-- drift"
                    elseif fault=="generation" then candidate(f,EDIT)
                    elseif fault=="binding" then enter(f,3)
                    else error(setmetatable({}, {__tostring=function() error("unsafe stringify") end})) end
                end
                v,e=f.p:InspectCandidate(FILE)
                eq(v,nil,fault.." changing analysis refused")
                eq(next(f.p._candidate_inspections),nil,fault.." refusal stores no plan")
                unchanged(f,before,fault.." inspection")
            end
            for _,fault in ipairs({"disk","generation","binding","release"}) do
                f=fixture();local before=f.capture.snapshot
                f.on_create=function()
                    f.on_create=nil
                    if fault=="disk" then f.disk=EDIT.."\n-- late drift"
                    elseif fault=="generation" then candidate(f,EDIT)
                    elseif fault=="binding" then enter(f,3)
                    else f.p:Release() end
                end
                v,e=f.p:InspectCandidate(FILE)
                eq(v,nil,fault.." late compilation drift refused")
                eq(next(f.p._candidate_inspections),nil,fault.." late inspection has no cache")
                unchanged(f,before,fault.." late inspection")
            end
            f=fixture();local before=f.capture.snapshot
            Cards.Describe=function() error("describe fixture failure") end
            v,e=f.p:InspectCandidate(FILE);Cards.Describe=old_describe
            eq(v,nil,"describe failure contained");unchanged(f,before,"describe failure")

            f=fixture();local before=f.capture.snapshot
            local at=EDIT:find(SIDE,1,true);candidate(f,EDIT:sub(1,at-1)..EDIT:sub(at+#SIDE))
            model=must(f.p:InspectCandidate(FILE))
            eq(#model.tombstones,1,"absent source class displayed, not deleted")
            eq(model.tombstones[1].definition_version,1,"source tombstone keeps published version")
            eq(row(model.cards,"card:1:L:1").pending,true,"missing source owner pending")
            unchanged(f,before,"tombstone")
            f=fixture()
            candidate(f,EDIT.."\n_tmp_sc=boss.card.New('D',1,2,3,100)\nfunction _tmp_sc:init(n) return n end\ntable.insert(_editor_class['K'].cards,_tmp_sc)")
            model=must(f.p:InspectCandidate(FILE))
            eq(#model.pending_sources,2,"new and unproven sibling sources displayed")
            eq(model.pending_sources[1].candidate_slot,3,"unproven sibling source slot")
            eq(model.pending_sources[2].candidate_slot,4,"new unowned source slot")
            eq(row(model.cards,"card:1:K:3").pending,true,"changed-layout sibling not guessed")
            check(scalar_tree(model.pending_sources),"unowned description excludes source descriptor")

            -- ImGui binding stub: proves layout consumption/control dispatch, not rendering.
            local texts,buttons,clicked={},{},""
            local function emit(text) texts[#texts+1]=text end
            package.loaded.imgui={ImVec4=function(...) return {...} end,ImGui={
                Text=emit,TextDisabled=emit,TextWrapped=emit,TextColored=function(_,t) emit(t) end,
                Separator=function() end,SameLine=function() end,CollapsingHeader=function() return true end,
                Button=function(label) buttons[#buttons+1]=label;return label==clicked end}}
            package.loaded["SpellHotReload.UI.Tab.MonitorTab"]=nil
            local Monitor=require("SpellHotReload.UI.Tab.MonitorTab")
            f=fixture();local view={plugin=f.p}
            clicked="Inspect Current##inspect_"..FILE
            Monitor.layout(view);has(view.last_result,"not committed","explicit inspection button")
            eq(f.restarts,0,"layout inspection no restart")
            clicked="";texts={};buttons={}
            local read_count,create_count,discoveries=f.reads,f.creates,f.discoveries
            Monitor.layout(view)
            local rendered=table.concat(texts,"\n")
            has(rendered,"published r0","UI shows actual revision")
            has(rendered,"not commit authorization","UI labels inspection not authority")
            has(rendered,"pending","UI shows pending wrappers/functions")
            has(rendered,"preserve-state","UI shows initializer boundary")
            has(rendered,"Published callbacks","UI shows per-callback versions")
            has(rendered,"Published observations","UI separates observation versions")
            eq(f.reads,read_count,"layout no disk polling");eq(f.creates,create_count,"layout no compile")
            eq(f.discoveries,discoveries,"layout no repeated Match")
            f.p._pending_restart_run={kind="versioned-card-restart"}
            buttons={};Monitor.layout(view)
            local labels=table.concat(buttons,"\n")
            check(not labels:find("Apply & Restart Current",1,true),"pending run disables new Apply button")
            has(labels,"Retry Restart","pending run retains retry button")
            f.p._pending_restart_run=nil
            clicked="Apply & Restart Current";Monitor.layout(view);has(view.last_result,"applied","UI Apply retains scoped dispatch")
            enter(f,2);clicked="";texts={};Monitor.layout(view)
            has(table.concat(texts,"\n"),"Last partial publication: r1","UI partial ledger shown")
            eq(f.p:GetCandidateInspection(FILE,Binding.CaptureCurrent()),nil,"UI cannot treat old inspection as commit plan")
        end
    end)
    debug.getupvalue,debug.setupvalue,debug.upvaluejoin=get,set,join
    if saved.jit then _G.jit=saved.jit end
    Binding.Restart,Card.Plan,Compose.Create=old_restart,old_plan,old_create
    require("SpellHotReload.Adapters.Card.CardVersions").Describe=old_describe
    for _,p in ipairs(plugins) do if not p:IsReleased() then p:Release() end end
    for _,name in ipairs(globals) do rawset(_G,name,saved[name]) end
    for _,name in ipairs(modules) do package.loaded[name]=loaded[name] end
    if not ok then failed=failed+1;failures[#failures+1]="unexpected error: "..tostring(problem) end
    print(string.format("MonitorVersionsSpec: %d passed / %d failed",passed,failed))
    for _,why in ipairs(failures) do print("  FAIL "..why) end
    return {passed=passed,failed=failed}
end
return M
