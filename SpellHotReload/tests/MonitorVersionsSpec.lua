                    elseif fault=="snapshot" then f.capture.snapshot={}
                    elseif fault=="release" then f.p:Release()
                    elseif fault=="throw" then error("Local describe fixture failure")
                    elseif fault=="scalar" then debug.setupvalue(f.entry.anchor,must(Anchor.Slot(f.entry,"state")),77) end
                    return result,why
                end
                local ok,display,why=pcall(f.p.InspectCandidate,f.p,FILE)
                Local.Describe=local_describe
                f.classes.K.cards[3].init=original_callback
                if not f.p:IsReleased() then
                    debug.setupvalue(f.entry.anchor,must(Anchor.Slot(f.entry,"helper")),original_helper)
                    f.capture.snapshot=before
                end
                eq(ok,true,fault.." owner description error remains contained")
                if fault=="scalar" then
                    must(display,why)
                    eq(Anchor.Get(f.entry,"state"),77,"ordinary scalar evolution is not frozen by inspection")
                    eq(row(display.functions,"local:helper").definition_version,1,"state change does not advance function version")
                else
                    eq(display,nil,fault.." late description change refuses inspection")
                    eq(next(f.p._candidate_inspections),nil,fault.." late description refuses to save a plan")
                end
                if fault~="release" then unchanged(f,before,fault.." late description") end
            end

            -- Domain projections must not retain a callback, metatable or cycle
            -- in the UI cache even if an owner description accidentally returns it.
            local card_describe=Card.Describe
            for _,fault in ipairs({"function","metatable","cycle"}) do
                f=fixture();before=f.capture.snapshot
                Card.Describe=function(...)
                    local description,why=card_describe(...)
                    if description then
                        if fault=="function" then description.cards[1].observed[1]=function() end
                        elseif fault=="metatable" then setmetatable(description.cards,{})
                        else description.cards[1].observed=description.cards end
                    end
                    return description,why
                end
                local ok,display,why=pcall(f.p.InspectCandidate,f.p,FILE)
                Card.Describe=card_describe
                eq(ok,true,fault.." malformed description is contained")
                eq(display,nil,fault.." malformed description is refused")
                has(why,"display values must",fault.." scalar-only boundary diagnosed")
                eq(next(f.p._candidate_inspections),nil,fault.." no domain objects retained in display cache")
                unchanged(f,before,fault.." malformed description")
            end

            -- In addition to candidate/snapshot/binding drift above, retire past
            -- results on cheap controller/driver/anchor/source-scope changes.
            for _,fault in ipairs({"driver","controller","anchor","source","file"}) do
                f=fixture();must(f.p:InspectCandidate(FILE))
                local binding=must(Binding.CaptureCurrent())
                local controller,anchor,source,file=f.p._commit,f.entry.anchor,f.entry.loaded_source,f.entry.file
                if fault=="driver" then f.p._driver_error={message="fixture driver fault"}
                elseif fault=="controller" then f.p._commit={Poisoned=function() return false end}
                elseif fault=="anchor" then f.entry.anchor=function() end
                elseif fault=="source" then f.entry.loaded_source=SOURCE.."\n-- foreign first load"
                else f.entry.file="Foreign_Boss.lua" end
                eq(f.p:GetCandidateInspection(FILE,binding),nil,fault.." past inspection retired")
                eq(next(f.p._candidate_inspections),nil,fault.." drops cached references")
                f.p._commit,f.entry.anchor,f.entry.loaded_source,f.entry.file=controller,anchor,source,file
                f.p._driver_error=nil
                eq(f.p:GetCandidateInspection(FILE,binding),nil,fault.." retired display cannot revive")
            end

            -- ImGui binding stub: proves layout consumption/control dispatch, not rendering.
            local texts,buttons,clicked={},{},""
            local function emit(text) texts[#texts+1]=text end
            package.loaded.imgui={ImVec4=function(...) return {...} end,ImGui={
                Text=emit,TextDisabled=emit,TextWrapped=emit,TextColored=function(_,t) emit(t) end,
                Separator=function() end,SameLine=function() end,CollapsingHeader=function() return true end,
                Button=function(label) buttons[#buttons+1]=label;return label==clicked end}}
            package.loaded["SpellHotReload.UI.Tab.MonitorTab"]=nil
            local Monitor=require("SpellHotReload.UI.Tab.MonitorTab")
            f=fixture();local view={plugin=f.p}
            clicked="Inspect Current##inspect_"..FILE
            Monitor.layout(view);has(view.last_result,"not committed","explicit inspection button")
            eq(f.restarts,0,"layout inspection no restart")
            clicked="";texts={};buttons={}
            local read_count,create_count,discoveries=f.reads,f.creates,f.discoveries
            Monitor.layout(view)
            local rendered=table.concat(texts,"\n")
            has(rendered,"published r0","UI shows actual revision")
            has(rendered,"File remainder:","UI separates file remainder from Current units")
            has(rendered,"selected may be unchanged","UI distinguishes selected from changed")
            has(rendered,"not permission","file preview is not Apply permission")
            has(rendered,"not commit authorization","UI labels inspection not authority")
            has(rendered,"pending","UI shows pending wrappers/functions")
            has(rendered,"preserve-state","UI shows initializer boundary")
            has(rendered,"Published callbacks","UI shows per-callback versions")
            has(rendered,"Published observations","UI separates observation versions")
            eq(f.reads,read_count,"layout no disk polling");eq(f.creates,create_count,"layout no compile")
            eq(f.discoveries,discoveries,"layout no repeated Match")
            f.p._pending_restart_run={kind="versioned-card-restart"}
            buttons={};Monitor.layout(view)
            local labels=table.concat(buttons,"\n")
            check(not labels:find("Apply & Restart Current",1,true),"pending run disables new Apply button")
            has(labels,"Retry Restart","pending run retains retry button")
            f.p._pending_restart_run=nil
            clicked="Apply & Restart Current";Monitor.layout(view);has(view.last_result,"applied","UI Apply retains scoped dispatch")
            enter(f,2);clicked="";texts={};Monitor.layout(view)
            has(table.concat(texts,"\n"),"Last partial publication: r1","UI partial ledger shown")
            eq(f.p:GetCandidateInspection(FILE,Binding.CaptureCurrent()),nil,"UI cannot treat old inspection as commit plan")

            f=fixture();candidate(f,object_edit);must(f.p:InspectCandidate(FILE))
            view={plugin=f.p};clicked=""
            package.loaded.imgui.ImGui.CollapsingHeader=function() return false end
            texts={};Monitor.layout(view);rendered=table.concat(texts,"\n")
            has(rendered,"1 uncovered top-level","collapsed summary retains uncovered count")
            has(rendered,"_editor_class['K'].extra","collapsed summary retains definition")
            has(rendered,"candidate line "..(newlines+2),"collapsed summary retains source line")
            has(rendered,"top-level change not published or not confirmed","collapsed summary retains reason")
            check(not rendered:find("Published callbacks",1,true),"unit details folded")
            view.last_result="compare: fixture refusal";texts={};Monitor.layout(view)
            has(table.concat(texts,"\n"),"Before commit / comparison refused:","file comparison stage shown")
            view.last_result="applied; completion unavailable: fixture";texts={};Monitor.layout(view)
            has(table.concat(texts,"\n"),"After commit / completion check:","failed completion stage shown")
            view.last_result="fixture unspecified failure";texts={};Monitor.layout(view)
            has(table.concat(texts,"\n"),"Result: fixture unspecified failure","unknown stage not inferred")
            FileApply.Remaining=function() return nil,{message="remainder UI failure"} end
            must(f.p:InspectCandidate(FILE));FileApply.Remaining=old_remaining
            texts={};Monitor.layout(view)
            has(table.concat(texts,"\n"),"File remainder unavailable: remainder UI failure","diagnostic failure remains visible")
        end
    end)
    debug.getupvalue,debug.setupvalue,debug.upvaluejoin=get,set,join
    if saved.jit then _G.jit=saved.jit end
    Restart.Handoff,Compose.Create=old_restart,old_create
    require("SpellHotReload.Adapters.Card.CardVersions").Describe=old_describe
    FileApply.Remaining=old_remaining
    for _,p in ipairs(plugins) do if not p:IsReleased() then p:Release() end end
    for _,name in ipairs(globals) do rawset(_G,name,saved[name]) end
    for _,name in ipairs(modules) do package.loaded[name]=loaded[name] end
    if not ok then failed=failed+1;failures[#failures+1]="unexpected error: "..tostring(problem) end
    print(string.format("MonitorVersionsSpec: %d passed / %d failed",passed,failed))
    for _,why in ipairs(failures) do print("  FAIL "..why) end
    return {passed=passed,failed=failed}
end
