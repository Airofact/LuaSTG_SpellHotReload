--------------------------------------------------------------------------------
--- SpellHotReload tests/CardSpec.lua
---
--- Regression spec for the card adapter. Card.lua must reproduce the card
--- pipeline the plugin already runs (CardCallbacks + PracticeBinding) through
--- the generic four-hook contract, so this spec drives a representative inline
--- card and a named-function card through both the legacy calls and the adapter
--- hooks and compares the observed behavior, then exercises the driver's
--- commit/restart split (live mutation vs retryable restart).
---
--- Runs under plain Lua 5.1 and LuaJIT with the game directory as cwd
--- (see tests/Run.lua).
--------------------------------------------------------------------------------

local Adapter = require("SpellHotReload.Adapter")
local NodeRegistry = require("SpellHotReload.NodeRegistry")
local Driver = require("SpellHotReload.Driver")
local CardCallbacks = require("SpellHotReload.Adapters.Card.CardCallbacks")
local Card = require("SpellHotReload.Adapters.Card.Card")
local Binding = require("SpellHotReload.Adapters.Card.PracticeBinding")
local Loader = require("SpellHotReload.GeneratedBossLoader")

local M = {}
local passed, failed = 0, 0
local failures = {}

local function check(cond, label)
    if cond then
        passed = passed + 1
    else
        failed = failed + 1
        failures[#failures + 1] = label
    end
end

local function eq(actual, expected, label)
    check(actual == expected,
        label .. " (expected " .. tostring(expected) .. ", got " .. tostring(actual) .. ")")
end

local GLOBALS = { "boss", "task", "_editor_class", "_sc_table", "_tmp_sc", "_other_init",
    "_boss", "IsValid", "lstg", "stage", "ext", "jit", "MOVE_NORMAL" }

function M.run()
    local saved = {}
    for _, key in ipairs(GLOBALS) do saved[key] = rawget(_G, key) end

    local ok, err = xpcall(function()
        ------------------------------------------------------------------------
        -- engine stand-ins (same shape InlineSpec uses)
        ------------------------------------------------------------------------
        local restarts, restart_fails = 0, false
        local defaults = {}
        for _, name in ipairs({ "before", "init", "frame", "render", "beforedel", "del", "after" }) do
            defaults[name] = function() end
        end
        boss = { card = { _default_card = defaults }, dialog = { New = function() return {} end } }
        MOVE_NORMAL = 1
        boss.move = { New = function() return { name = "", is_sc = false } end }
        boss.card.New = function(name)
            local card = { name = name, is_sc = name ~= "" }
            for key, value in pairs(defaults) do card[key] = value end
            return card
        end
        task = { New = function(self, fn) self.task = coroutine.create(fn) end }

        ext = nil
        lstg = { var = {} }
        stage = { group = { PracticeStart = function(name)
            assert(name == "Spell Practice@Spell Practice")
            if restart_fails then error("restart test failure") end
            restarts = restarts + 1
        end } }

        local function load_source(source)
            _editor_class, _sc_table = {}, {}
            local names = Loader.ListFunctionNames(source)
            return assert((loadstring or load)(source .. "\n" .. Loader.BuildTrailer(names)))()
        end

        local function fixture(version, prefix, init)
            return table.concat({
                "-- Generated by LuaSTG Editor Sharp",
                prefix or "local counter, absent, disabled = 10, nil, false",
                '_editor_class["Boss:Normal"] = {}',
                '_editor_class["Boss:Normal"].cards = {}',
                '_tmp_sc = boss.dialog.New(true)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Normal"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:init() end',
                'table.insert(_editor_class["Boss:Normal"].cards, _tmp_sc)',
                '_tmp_sc = boss.card.New("Inline", 1, 2, 3, 100, {}, false)',
                'function _tmp_sc:before() counter = counter + 1; self.before_value = counter end',
                'function _tmp_sc:init()',
                init or ('task.New(self, function()\n'
                    .. '  local total = 0\n'
                    .. '  for i=1,3 do if i > 0 then total=total+i end end\n'
                    .. '  coroutine.yield()\n'
                    .. '  self.value = total + ' .. version .. '\n'
                    .. '  self.absent, self.disabled = absent, disabled\n'
                    .. 'end)'),
                'end',
                'function _tmp_sc:frame() self.frame_value = ' .. version .. ' end',
                '_tmp_sc.render = function(self) self.render_value = counter end',
                '_tmp_sc.perform=false',
                'table.insert(_editor_class["Boss:Normal"].cards,_tmp_sc)',
                'table.insert(_sc_table,{"Boss:Normal","Inline",_tmp_sc,3,false})',
            }, "\n")
        end

        local function run_init(actor, card)
            card.init(actor)
            if actor.task ~= nil then
                assert(coroutine.resume(actor.task))
                assert(coroutine.resume(actor.task))
            end
        end

        local function live_names(content, class_key)
            local layout = assert(CardCallbacks.Read(content, class_key))
            local names = {}
            for i, entry in ipairs(layout) do names[i] = entry.name or "" end
            return names
        end

        local old, new = fixture(1), fixture(20)

        ------------------------------------------------------------------------
        -- contract + registry routing
        ------------------------------------------------------------------------
        eq(Adapter.Validate(Card), true, "card: satisfies the adapter contract")
        eq(Card.Restartable, true, "card: declares a restartable commit")
        local registry = NodeRegistry.New()
        eq(registry:Register("card", Card), true, "card: registers a carrier")
        local probe = Card.Node(assert(Card.Request({ class_key = "Boss:Normal", card = {}, slot = 3 })))
        eq(registry:For(probe), Card, "card: registry routes the card carrier")
        check(Adapter.Validate(registry:For(probe)), "card: routed adapter stays valid")
        check(registry:For({ carrier = "card" }) == Card, "card: a bare card node routes too")

        ------------------------------------------------------------------------
        -- Locate agrees with CardCallbacks.Select case by case
        ------------------------------------------------------------------------
        local cases = {
            { name = "named slot", candidate = new, class_key = "Boss:Normal", target = 3, accepts = true },
            { name = "dialog slot", candidate = new, class_key = "Boss:Normal", target = 1, accepts = false },
            { name = "missing class", candidate = new, class_key = "Missing", target = 3, accepts = false },
            { name = "changed metadata", candidate = new:gsub('"Inline", 1', '"Renamed", 1'),
              class_key = "Boss:Normal", target = 3, accepts = false },
            { name = "syntax error", candidate = new .. "\nthis is not Lua",
              class_key = "Boss:Normal", target = 3, accepts = false },
        }
        for _, case in ipairs(cases) do
            local legacy = CardCallbacks.Select(old, case.candidate, case.class_key, case.target)
            local handle = Card.Locate(
                assert(Card.Request({ class_key = case.class_key, card = {}, slot = case.target })),
                { original = old, content = case.candidate })
            eq(legacy ~= nil, case.accepts, "locate: legacy decision for " .. case.name)
            eq(handle ~= nil, case.accepts, "locate: adapter decision for " .. case.name)
            if legacy ~= nil and handle ~= nil then
                eq(handle.descriptor.constructor, legacy.constructor,
                    "locate: same constructor as Select for " .. case.name)
                eq(handle.descriptor.callbacks.init, legacy.callbacks.init,
                    "locate: same init source as Select for " .. case.name)
            end
        end
        do
            local request = assert(Card.Request({ class_key = "Boss:Normal", card = {} }))
            check(Card.Locate(request, {}) == nil, "locate: missing loaded source is rejected")
            check(Card.Locate(assert(Card.Request({ class_key = "Boss:Normal", card = {}, slot = 3 })),
                { original = old }) == nil, "locate: missing candidate source is rejected")
        end

        ------------------------------------------------------------------------
        -- equivalence: the legacy pipeline and the adapter observe the same
        ------------------------------------------------------------------------
        local function observe_legacy(source, candidate)
            restarts = 0
            local captured = load_source(source)
            local live = _editor_class["Boss:Normal"].cards[3]
            local actor = {}
            local descriptor = assert(CardCallbacks.Select(source, candidate, "Boss:Normal", 3))
            local plan = assert(CardCallbacks.Build(descriptor, live, candidate, captured))
            CardCallbacks.Publish(live, plan)
            Binding.Restart("Boss:Normal", "Inline", live, 3, false)
            run_init(actor, live)
            live.before(actor); live.render(actor)
            return {
                value = actor.value, absent = actor.absent, disabled = actor.disabled,
                render = actor.render_value, restarts = restarts,
                handoff = table.concat({ tostring(_sc_table.EXT_POS[1]),
                    tostring(_sc_table.EXT_POS[4]), tostring(_sc_table.EXT_POS[5]) }, ","),
                handoff_card = _sc_table.EXT_POS[3] == live,
                live_identity = _editor_class["Boss:Normal"].cards[3] == live,
            }
        end

        local function observe_adapter(source, candidate)
            restarts = 0
            local captured = load_source(source)
            local live = _editor_class["Boss:Normal"].cards[3]
            local actor = {}
            local request = assert(Card.Request({
                class_key = "Boss:Normal", card = live, slot = 3, name = "Inline",
            }))
            local run = assert(Card.Plan(request, {
                file = "Test_Boss.lua", original = source, content = candidate, registry = captured,
            }))
            local report = Driver.New():Commit(run)
            eq(report.committed, 1, "commit: one live mutation")
            run_init(actor, live)
            live.before(actor); live.render(actor)
            return {
                value = actor.value, absent = actor.absent, disabled = actor.disabled,
                render = actor.render_value, restarts = restarts,
                handoff = table.concat({ tostring(_sc_table.EXT_POS[1]),
                    tostring(_sc_table.EXT_POS[4]), tostring(_sc_table.EXT_POS[5]) }, ","),
                handoff_card = _sc_table.EXT_POS[3] == live,
                live_identity = _editor_class["Boss:Normal"].cards[3] == live,
            }
        end

        local want = observe_legacy(old, new)
        local got = observe_adapter(old, new)
        for _, field in ipairs({ "value", "render", "restarts", "handoff", "handoff_card", "live_identity" }) do
            eq(got[field], want[field], "equivalence: adapter matches legacy on " .. field)
        end
        eq(want.value, 26, "equivalence: the fixture publishes the expected value")
        eq(want.render, 11, "equivalence: callbacks keep the shared local state")

        ------------------------------------------------------------------------
        -- equivalence for the named-function build path
        ------------------------------------------------------------------------
        local function named_fixture(version, argument)
            return fixture(version,
                'local counter, absent, disabled = 10,nil,false\n'
                .. 'local function pattern(self,n) self.value=n+' .. version .. ' end',
                'pattern(self,' .. argument .. ')')
                .. '\n_other_init = function(self) pattern(self,1) end'
        end
        local named_old, named_new = named_fixture(1, 1), named_fixture(40, 2)

        local function observe_named(source, candidate, use_adapter)
            restarts = 0
            local captured = load_source(source)
            local live = _editor_class["Boss:Normal"].cards[3]
            local actor, other, functions = {}, {}, nil
            if use_adapter then
                local request = assert(Card.Request({
                    class_key = "Boss:Normal", card = live, slot = 3, name = "Inline",
                }))
                local run = assert(Card.Plan(request, {
                    file = "Test_Boss.lua", original = source, content = candidate, registry = captured,
                }))
                functions = run.plan.functions
                assert(Driver.New():Commit(run))
            else
                local descriptor = assert(CardCallbacks.Select(source, candidate, "Boss:Normal", 3))
                local plan = assert(CardCallbacks.Build(descriptor, live, candidate, captured))
                functions = plan.functions
                CardCallbacks.Publish(live, plan)
            end
            run_init(actor, live)
            if _G._other_init ~= nil then _G._other_init(other) end
            return { value = actor.value, other = other.value, functions = functions }
        end

        local named_want = observe_named(named_old, named_new, false)
        local named_got = observe_named(named_old, named_new, true)
        eq(named_want.value, 42, "equivalence: named fixture publishes the expected value")
        eq(named_got.value, named_want.value, "equivalence: named function body matches")
        eq(named_got.other, named_want.other, "equivalence: shared named cell matches other variants")
        eq(type(named_got.functions.pattern), "function", "inject: rebuilt named function is exposed")
        _G._other_init = nil

        ------------------------------------------------------------------------
        -- driver: Commit is the only live mutation; Restart is retryable
        ------------------------------------------------------------------------
        restarts, restart_fails = 0, false
        local captured = load_source(old)
        local live = _editor_class["Boss:Normal"].cards[3]
        local driver = Driver.New()
        local function request_for(card, binding)
            return assert(Card.Request({
                class_key = "Boss:Normal", card = card, slot = 3, name = "Inline", binding = binding,
            }))
        end
        local function plan_for(card, candidate, binding)
            return assert(Card.Plan(request_for(card, binding), {
                file = "Test_Boss.lua", original = old, content = candidate, registry = captured,
            }))
        end

        local before_init = live.init
        local run = plan_for(live, new)
        eq(live.init, before_init, "plan: the live card is untouched")
        eq(run.planned, 1, "plan: a single planned entry")
        check(run.entries[1].status == "planned" and run.entries[1].adapter == Card,
            "plan: the entry carries the card adapter")
        local report = driver:Commit(run)
        eq(report.committed, 1, "commit: reports one commit")
        eq(restarts, 1, "commit: the stage restarted once")
        check(live.init ~= before_init, "commit: published the rebuilt callbacks")
        check(run.plan.restart ~= nil and run.plan.restart.class_key == "Boss:Normal"
            and run.plan.restart.slot == 3, "commit: restart context recorded")
        eq(Driver.Count(run, "committed"), 1, "commit: the entry is marked committed")

        restart_fails = true
        local failing = plan_for(live, fixture(50))
        local fail_report = driver:Commit(failing)
        eq(fail_report.committed, 1, "restart failure: definitions still committed")
        eq(#fail_report.restarts, 1, "restart failure: restart reported")
        eq(fail_report.restarts[1].ok, false, "restart failure: marked failed")
        eq(restarts, 1, "restart failure: the stage did not restart")
        local committed_init = live.init
        restart_fails = false
        local retry = driver:Restart(failing)
        eq(retry.retried, 1, "restart retry: attempted")
        eq(retry.ok, 1, "restart retry: succeeded")
        eq(restarts, 2, "restart retry: the stage restarted")
        check(live.init == committed_init, "restart retry: does not recompile")
        eq(driver:Commit(failing).committed, 0, "restart retry: a second commit is a no-op")

        ------------------------------------------------------------------------
        -- rename, rejection and switch coverage through the adapter
        ------------------------------------------------------------------------
        local renamed = new:gsub('"Inline", 1', '"Renamed", 1')
        local run_rename = plan_for(live, renamed,
            { slot = 3, name = "Inline", names = live_names(old, "Boss:Normal") })
        assert(driver:Commit(run_rename))
        eq(run_rename.handle.match, "renamed in place", "rename: matched in place")
        eq(_sc_table.EXT_POS[2], "Renamed", "rename: restart hands off the new name")
        eq(_sc_table.EXT_POS[3], live, "rename: restart keeps the live card")
        local actor = {}
        run_init(actor, live)
        eq(actor.value, 26, "rename: the reloaded body still applies")

        local unknown = fixture(30, 'local counter, absent, disabled, unknown = 10,nil,false,7',
            'self.value=unknown')
        local bad, reason = Card.Plan(request_for(live), {
            file = "Test_Boss.lua", original = old, content = unknown, registry = captured,
        })
        eq(bad, nil, "inject: a new uncaptured local is rejected")
        check(type(reason) == "string" and reason:find("uncaptured local", 1, true) ~= nil,
            "inject: the rejection names the uncaptured local (" .. tostring(reason) .. ")")

        local before_malicious = live.init
        local malicious = new .. '\nerror("generated wiring must not run")'
        assert(plan_for(live, malicious))
        eq(live.init, before_malicious, "plan: generated wiring and callback bodies never run")

        restarts = 0
        local run_norestart = plan_for(live, new)
        local no_restart = driver:Commit(run_norestart, { restart = false })
        eq(no_restart.committed, 1, "restart=false: the publish still commits")
        eq(restarts, 0, "restart=false: the stage does not restart")
        eq(#no_restart.restarts, 0, "restart=false: no restart is recorded")

        local no_frame = new:gsub('function _tmp_sc:frame%(%) self.frame_value = 20 end', '')
        assert(driver:Commit(plan_for(live, no_frame)))
        eq(live.frame, defaults.frame, "deleted frame callback restores the default")

        local bad_plan, missing = Card.Plan(request_for(live), { content = new })
        eq(bad_plan, nil, "plan: a request without the loaded source is rejected")
        check(type(missing) == "string" and missing:find("loaded source", 1, true) ~= nil,
            "plan: the rejection explains the missing source (" .. tostring(missing) .. ")")
    end, debug.traceback)

    for _, key in ipairs(GLOBALS) do _G[key] = saved[key] end
    if not ok then error(err, 0) end

    print(string.format("[SpellHotReload card] %d passed, %d failed", passed, failed))
    for _, label in ipairs(failures) do
        print("  FAIL: " .. label)
    end
    return { passed = passed, failed = failed, failures = failures }
end

return M
