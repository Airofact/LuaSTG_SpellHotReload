-- Real normal-load capture, Native syntax, dependency routing and common commit.
-- Engine Class/card stand-ins are explicit; this is not an engine/performance run.
local M={}
function M.run()
    -- These module bindings belong to this spec's isolated Capsule. Watcher.New
    -- does not start an OS watcher; any accidental Start must fail this spec.
    local watcher_name,action_name="lstg.FileSystemWatcher","lstg.FileSystemWatcher.FileAction"
    local saved_watcher,saved_actions=package.loaded[watcher_name],package.loaded[action_name]
    local watcher_creates=0
    package.loaded[watcher_name]={create=function()
        watcher_creates=watcher_creates+1
        error("ClassSpellSpec must not start an OS watcher")
    end}
    package.loaded[action_name]={}
    local Plugin=require("SpellHotReload.Runtime.Plugin")
    local Class=require("SpellHotReload.Adapters.Class.Class")
    local Observe=require("SpellHotReload.Adapters.Class.ClassLoad")
    local Card=require("SpellHotReload.Adapters.Card.Card")
    local Local=require("SpellHotReload.Adapters.Local.Local")
    local Files=require("SpellHotReload.Pipeline.FileVersions")
    local Source=require("SpellHotReload.Source.FileAnalysis")
    local Anchor=require("SpellHotReload.Load.Anchor")
    local Watcher=require("SpellHotReload.Runtime.Watcher")
    local FileApply=require("SpellHotReload.Apply.FileApply")
    local names={"init","del","frame","render","colli","kill"}
    local callbacks={"before","init","frame","render","beforedel","del","after"}
    local globals={"Class","object","_object","bullet","enemy","laser","laser_bent","boss","all_class",
        "_editor_class","_tmp_sc","_sc_table","lstg","ext","IsValid"}
    local saved={};for _,name in ipairs(globals) do saved[name]=rawget(_G,name) end
    local plugins={};local passed,failed,failures=0,0,{}
    local function eq(a,b,label) assert(rawequal(a,b),label..": "..tostring(a).." ~= "..tostring(b));passed=passed+1 end
    local function must(v,e) assert(v,type(e)=="table" and e.message or e);return v end
    local function case(label,body)
        local ok,err=xpcall(body,debug.traceback)
        if not ok then failed=failed+1;failures[#failures+1]=label..": "..tostring(err) end
    end
    local function source(base,external)
        local rows={"-- Generated by LuaSTG Editor Sharp","local state=3","local init_count=0",
            "local function helper(n) return state+n end"}
        if not external then rows[#rows+1]="_editor_class['K']=Class("..(base or "boss")..")" end
        rows[#rows+1]="_editor_class['K'].cards={}"
        rows[#rows+1]="_editor_class['K'].name='K'"
        rows[#rows+1]="_editor_class['K'].init=function(self) init_count=init_count+1;self.c=helper(1) end"
        rows[#rows+1]="_editor_class['K'].frame=function(self) self.c=helper(2) end"
        rows[#rows+1]="_tmp_sc=boss.card.New('A',1,2,3,100)"
        rows[#rows+1]="function _tmp_sc:init() init_count=init_count+1;self.a=helper(3) end"
        rows[#rows+1]="table.insert(_editor_class['K'].cards,_tmp_sc)"
        rows[#rows+1]="_tmp_sc=boss.card.New('B',1,2,3,100)"
        rows[#rows+1]="function _tmp_sc:init() self.b=40 end"
        rows[#rows+1]="table.insert(_editor_class['K'].cards,_tmp_sc)"
        return table.concat(rows,"\n")
    end
    local file="ClassSpell_Boss.lua"
    local function fixture(base,external)
        local f={constructs=0,cards=0,commits=0}
        _G.lstg={var={},Log=function() end};_G.ext={replay={IsReplay=function() return false end}}
        _G.IsValid=function() return true end
        _G.all_class={};_G._editor_class={};_G._sc_table={}
        _G.Class=function(parent)
            assert(type(parent)=="table" and parent.is_class)
            f.constructs=f.constructs+1
            local c={0,0,0,0,0,0,is_class=true,base=parent}
            for _,name in ipairs(names) do c[name]=parent[name] end
            all_class[#all_class+1]=c;return c
        end
        _G.object={is_class=true}
        for i,name in ipairs(names) do object[name]=function() end;object[i]=object[name] end
        for _,name in ipairs({"_object","bullet","enemy","laser","laser_bent","boss"}) do _G[name]=_G.Class(object) end
        local defaults={};for _,name in ipairs(callbacks) do defaults[name]=function() end end
        boss.card={_default_card=defaults,New=function(name)
            f.cards=f.cards+1;local c={name=name,is_combat=true}
            for _,key in ipairs(callbacks) do c[key]=defaults[key] end
            return c
        end}
        if external then _editor_class.K=_G.Class(boss) end
        f.constructs=0
        f.initial=source(base,external);f.content=f.initial
        f.p=Plugin.New();plugins[#plugins+1]=f.p
        f.entry=must(Observe.Capture(f.initial,{name=file}));must(f.p:AdoptLoad(file,f.entry))
        f.capture,f.refusal=f.p:GetVersions(file)
        f.cls=_editor_class.K;f.a=f.cls.cards[1];f.b=f.cls.cards[2]
        for _,c in ipairs(all_class) do for i,name in ipairs(names) do c[i]=c[name] end end
        f.p._activated,f.p._supported,f.p._sandbox_ok=true,true,true;f.p._activation_attempted=true
        f.p:GetStore():SetAccepted(file,f.initial,"fixture genuine load")
        f.p._watcher=Watcher.New({root="mod/Test",store=f.p:GetStore(),quiet_frames=1,read_gap=1})
        f.p._watcher.ReadFile=function()
            if f.on_read then f.on_read(f) end
            return f.content
        end
        f.kernel=f.p._commit.Commit
        f.p._commit.Commit=function(self,...)
            f.commits=f.commits+1;f.in_commit=true
            local receipt,err=f.kernel(self,...)
            f.in_commit=false;f.receipt,f.error=receipt,err
            return receipt,err
        end
        return f
    end
    local function apply(f,bytes)
        f.content=bytes;f.receipt,f.error=nil,nil
        local store=f.p:GetStore();local c=store:BeginCandidate(file,store._next_generation,"class/spell spec")
        must(store:RecordFirstRead(file,c.generation,bytes,1));must(store:VerifyStable(file,c.generation,bytes,2,1))
        return f.p:ApplyFileFromUI(file)
    end
    local function group(f,owner) return must(Files.GetAdapterRecords(f.capture,owner)) end
    local function has_edge(g,a,b)
        for _,edge in ipairs(g.edges) do if edge.consumer==a and edge.provider==b then return true end end
        return false
    end
    case("genuine first load creates separate cards with actual Class providers",function()
        local f=fixture();must(f.capture,f.refusal)
        local cg,sg,lg=group(f,Class),group(f,Card),group(f,Local)
        eq(#f.capture.snapshot.owners,3,"one owner for Local/Class/Spell")
        eq(f.capture.snapshot.owners[2].owner,Class,"Class is captured before Spell")
        eq(#cg.units,1,"one genuine Class unit")
        eq(#sg.units,2,"same-class cards have distinct published units")
        local a,b=sg.state.units[sg.state.order[1]],sg.state.units[sg.state.order[2]]
        eq(a.unit_ref==b.unit_ref,false,"one ref per actual card")
        eq(a.class_ref,cg.state.by_key.K.unit_ref,"A names original class ref")
        eq(b.class_ref,a.class_ref,"B shares provider, not card unit identity")
        eq(has_edge(sg,a.unit_ref,a.class_ref),true,"A -> Class is published")
        eq(has_edge(sg,b.unit_ref,b.class_ref),true,"B -> Class is published")
        eq(has_edge(cg,a.class_ref,lg.state.by_name.helper.unit_ref),true,"readonly Class -> Local capture edge is published")
        eq(f.constructs,1,"normal source constructed the class exactly once")
        eq(f.cards,2,"normal source constructed two cards")
        eq(Anchor.Get(f.entry,"init_count"),0,"capture called no class/card init")
    end)
    case("six consecutive Apply steps keep state and publish common actual versions",function()
        local f=fixture("_object");must(f.capture,f.refusal)
        local class_ref=group(f,Class).state.by_key.K.unit_ref
        local a_ref=group(f,Card).state.units["card:1:K:1"].unit_ref
        local b_version=group(f,Card).state.units["card:1:K:2"].definition_version
        local a_changed=f.initial:gsub("self.a=helper%(3%)","self.a=helper(30)")
        local both=a_changed:gsub("self.c=helper%(2%)","self.c=helper(20)")
        local helper=both:gsub("return state%+n","return state+n+10")
        local inputs={f.initial.."\n-- unchanged 1\n",a_changed,a_changed.."\n-- unchanged 2\n",both,both.."\n-- unchanged 3\n",helper}
        local revisions={0,1,1,2,2,3};local changed={false,true,false,true,false,true}
        for i,bytes in ipairs(inputs) do
            local message=apply(f,bytes)
            must(f.receipt,message);eq(f.receipt.changed,changed[i],"real changed receipt step "..i)
            eq(f.capture.snapshot.revision,revisions[i],"one common revision step "..i)
            eq(f.p:GetStore():GetCandidate(file),nil,"candidate completed step "..i)
            eq(group(f,Class).state.by_key.K.unit_ref,class_ref,"Class identity remains step "..i)
            eq(group(f,Card).state.units["card:1:K:1"].unit_ref,a_ref,"A identity remains step "..i)
            eq(group(f,Card).state.units["card:1:K:2"].definition_version,b_version,"unmodified B callback version remains step "..i)
            eq(Anchor.Get(f.entry,"init_count"),0,"Apply never invokes init step "..i)
        end
        eq(f.constructs,1,"no candidate Class execution")
        eq(f.cards,2,"no candidate card constructor execution")
        local obj={};f.cls[3](obj);eq(obj.c,33,"class method uses updated Local cell")
        f.a.init(obj);eq(obj.a,43,"A uses same updated Local cell")
        eq(Anchor.Get(f.entry,"init_count"),1,"only explicit lifecycle invocation changes counter")
    end)
    case("Spell B routes through readonly Class to changed Local helper",function()
        local f=fixture();must(f.capture,f.refusal)
        local before_class=f.cls.init;local before_b=f.b.init
        local bytes=f.initial:gsub("return state%+n","return state+n+10")
        local facts=must(Source.Build(bytes));local d=must(f.p:GetDriver():DiscoverPublished(file,facts,must(Files.Publication(f.capture)),{capture=f.capture,generation=1}))
        local binding={class_key="K",slot=2,card=f.b,name="B",names={"A","B"},mode="practice",include_previous=false}
        local function live() return {capture=f.capture,snapshot=f.capture.snapshot,entry=f.entry,session_id=f.capture.snapshot.session_id,
            classes=_editor_class,content=bytes,generation=1,binding=binding} end
        local card_view;for _,g in ipairs(d.reconciliation.groups) do if g.owner==Card then card_view=g.view end end
        local root,target=Card.CurrentRoot(card_view,Card.FreezeBinding(binding),f.capture,live());must(root,target)
        local op={capture=f.capture,base_snapshot=f.capture.snapshot,source=facts,file=file,entry=f.entry,anchor=f.entry.anchor,
            loaded_source=f.entry.loaded_source,session_id=f.capture.snapshot.session_id,generation=1,mode="current",roots={root},
            card={refresh=live,target=target}}
        local prepared,report=FileApply.Prepare(f.p:GetDriver(),d,op);must(prepared,report)
        local seen_class,seen_local=false,false
        for _,owner in ipairs(prepared.dependencies.owners) do for _,u in ipairs(owner.units) do
            if owner.owner==Class and u.unit_ref==group(f,Class).state.by_key.K.unit_ref then
                seen_class=true;eq(#u.roots[1].conditions,1,"selectorless current path carries Class condition")
            end
            if owner.owner==Local and u.unit_ref==group(f,Local).state.by_name.helper.unit_ref then seen_local=true end
        end end
        eq(seen_class,true,"current Spell root selected its real Class provider")
        eq(seen_local,true,"recursive Class -> Local need is resolved")
        for _,entry in ipairs(prepared.entries) do
            if entry.owner==Class then eq(#entry.fragment.raw_writes,0,"readonly Class provides evidence without writes") end
        end
        local ran,receipt,err=f.p._commit:Run(function(token)
            return f.p:GetDriver():CommitDiscovery(prepared,function(operation,fragments)
                return f.p._commit:Commit(token,operation,fragments,live(),FileApply.Refresh(operation,live))
            end)
        end)
        must(ran,receipt);must(receipt,err);eq(receipt.changed,true,"only routed helper update still has real changed receipt")
        eq(f.cls.init,before_class,"readonly Class method not replaced")
        eq(f.b.init,before_b,"B callback not replaced")
        local obj={};f.cls.init(obj);eq(obj.c,14,"existing class closure sees updated helper through original cell")
    end)
    case("unpublishable class definition blocks its Spell update",function()
        local f=fixture();must(f.capture,f.refusal);local before=f.capture.snapshot;local a=f.a.init
        apply(f,f.initial:gsub("self.c=helper%(1%)","self.c=helper(100)"):gsub("self.a=helper%(3%)","self.a=helper(30)"))
        eq(f.capture.snapshot,before,"readonly definition drift prevents dependent publication")
        eq(f.a.init,a,"dependent Spell was not partially installed")
        eq(f.p:GetStore():GetCandidate(file)~=nil,true,"blocked candidate remains")
        eq(f.constructs,1,"refusal never replays Class")
    end)
    case("live class cannot replace missing genuine Class history",function()
        local f=fixture("boss",true)
        eq(f.capture,nil,"external live class did not fabricate a same-file provider")
        eq(f.constructs,0,"only pre-existing external class was present")
        eq(Anchor.Get(f.entry,"init_count"),0,"refusal invokes no lifecycle callback")
    end)
    case("Class prepare failure preserves all owners",function()
        local f=fixture("_object");must(f.capture,f.refusal);local before=f.capture.snapshot;local a=f.a.init
        local inject=Class.Inject
        Class.Inject=function(handle,unit,context)
            if context.scope=="owner" and context.phase=="prepare" then return nil,{phase="inject",code="unsupported",message="intentional Class prepare failure"} end
            return inject(handle,unit,context)
        end
        local ok,err=pcall(apply,f,f.initial:gsub("self.a=helper%(3%)","self.a=helper(30)"))
        Class.Inject=inject;must(ok,err)
        eq(f.capture.snapshot,before,"prepare failure preserved common version")
        eq(f.a.init,a,"prepare failure installed no Spell callback")
        eq(f.commits,0,"prepare failure never reached common publisher")
    end)
    for _,fault in ipairs({"pair","snapshot"}) do
        case("mutate-then-throw rollback: "..fault,function()
            local f=fixture("_object");must(f.capture,f.refusal)
            local before=f.capture.snapshot;local frame,slot,a,helper=f.cls.frame,f.cls[3],f.a.init,Anchor.Get(f.entry,"helper")
            local index,raw
            for i=1,100 do local name,value=debug.getupvalue(f.kernel,i);if not name then break end;if name=="raw_write" then index,raw=i,value;break end end
            must(index,"common raw-write seam missing")
            local injected=false
            debug.setupvalue(f.kernel,index,function(target,key,value)
                raw(target,key,value)
                if not injected and (fault=="pair" and target==f.cls and key==3 or fault=="snapshot" and target==f.capture and key=="snapshot") then
                    injected=true;error("intentional mutation then failure")
                end
            end)
            local bytes=f.initial:gsub("return state%+n","return state+n+10")
                :gsub("self.c=helper%(2%)","self.c=helper(20)"):gsub("self.a=helper%(3%)","self.a=helper(30)")
            local ok,err=pcall(apply,f,bytes);debug.setupvalue(f.kernel,index,raw);must(ok,err)
            eq(injected,true,"requested failure seam reached")
            eq(f.receipt,nil,"failed transaction produced no success receipt")
            eq(f.capture.snapshot,before,"common snapshot rolled back")
            eq(f.cls.frame,frame,"Class named method rolled back")
            eq(f.cls[3],slot,"Class dispatch slot rolled back")
            eq(f.a.init,a,"Spell callback rolled back")
            eq(Anchor.Get(f.entry,"helper"),helper,"Local shared cell rolled back")
            eq(f.p._commit:Poisoned(),false,"successful rollback kept session usable")
            eq(f.p:GetStore():GetCandidate(file)~=nil,true,"failed candidate remains")
        end)
    end
    for _,plugin in ipairs(plugins) do plugin:Release() end
    for _,name in ipairs(globals) do rawset(_G,name,saved[name]) end
    package.loaded[watcher_name],package.loaded[action_name]=saved_watcher,saved_actions
    eq(watcher_creates,0,"no OS watcher was started by the isolated Apply cases")
    return {passed=passed,failed=failed,failures=failures}
end
return M
